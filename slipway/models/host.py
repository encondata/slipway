"""Deployment targets: Linux machines running Docker, reached over SSH."""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Any

from sqlalchemy import ForeignKey, String, Text
from sqlalchemy.orm import Mapped, mapped_column

from slipway.core.crypto import EncryptedText
from slipway.db.base import Base, Timestamps, UUIDPrimaryKey


class HostAuthMethod(StrEnum):
    KEY = "key"  # private key (pasted, or generated by Slipway)
    PASSWORD = "password"


class HostStatus(StrEnum):
    UNKNOWN = "unknown"
    HEALTHY = "healthy"
    WARNING = "warning"  # reachable, but Docker unavailable or resources under pressure
    UNREACHABLE = "unreachable"
    ERROR = "error"  # e.g. host key mismatch


class Host(UUIDPrimaryKey, Timestamps, Base):
    __tablename__ = "hosts"

    name: Mapped[str] = mapped_column(String(64), unique=True)
    hostname: Mapped[str] = mapped_column(String(255))
    port: Mapped[int] = mapped_column(default=22)
    username: Mapped[str] = mapped_column(String(64))
    environment: Mapped[str] = mapped_column(String(32), default="")  # prod / staging / dev ...
    description: Mapped[str] = mapped_column(String(255), default="")
    deploy_root: Mapped[str] = mapped_column(String(255), default="/opt/slipway")
    # Address the reverse proxy uses to reach this host's published ports, when it is not ``hostname``
    # (Slipway reaching the host by another name or over a VPN, say).
    proxy_address: Mapped[str | None] = mapped_column(String(255))

    auth_method: Mapped[str] = mapped_column(String(16), default=HostAuthMethod.KEY)
    private_key: Mapped[str | None] = mapped_column(EncryptedText)
    key_passphrase: Mapped[str | None] = mapped_column(EncryptedText)
    password: Mapped[str | None] = mapped_column(EncryptedText)
    # OpenSSH public key matching private_key, shown so it can be added to authorized_keys.
    public_key: Mapped[str | None] = mapped_column(Text)

    # Trust-on-first-use host key pinning.
    host_key: Mapped[str | None] = mapped_column(Text)
    host_key_fingerprint: Mapped[str | None] = mapped_column(String(128))

    status: Mapped[str] = mapped_column(String(16), default=HostStatus.UNKNOWN)
    last_checked_at: Mapped[datetime | None]
    last_error: Mapped[str | None] = mapped_column(Text)
    docker_version: Mapped[str | None] = mapped_column(String(64))
    os_info: Mapped[str | None] = mapped_column(String(255))
    # {"cpu_percent", "mem_percent", "mem_total_mb", "cpus", "containers_running"}
    metrics: Mapped[dict[str, Any]] = mapped_column(default=dict)

    created_by_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))

    @property
    def address(self) -> str:
        return self.hostname if self.port == 22 else f"{self.hostname}:{self.port}"

    @property
    def upstream_address(self) -> str:
        """Where the reverse proxy sends traffic for this host's published ports."""
        return self.proxy_address or self.hostname

    @property
    def is_pinned(self) -> bool:
        return bool(self.host_key)
