"""The ESXi provider of the machines core (phase 5 §8.2-§8.5, §9.11).

``EsxiProvider`` makes, checks, resizes, snapshots and removes Slipway's VMs on a standalone ESXi host, through
the client in ``slipway/services/esxi.py`` (``esxi.session`` and its ``EsxiApi``). A new VM is an empty VM
carrying Slipway's two markers and its cloud-init settings in guestinfo; the seed VM's single disk is copied in
thin, attached and grown; then the VM is powered on and pinned with the host key Slipway generated at plan time.
The machines core (``machines.py``) drives it: it pins the key, sets up Docker and marks the VM ready.

Rules every method keeps:

* A VM is Slipway's only when its name is the machine's and its markers name this machine and this environment
  (D20). The machine's frozen ``spec.api_host`` must still be the account's API host, or nothing is touched.
* The instance UUID is recorded the moment ``create_vm`` answers (``machines.record_vm``), so a retry finds the
  VM; a VM made but not recorded is found again by its name and markers and adopted (``machine.adopt``).
* Every task Slipway starts is in ``machines.last_task`` before Slipway waits on it (M5). A task someone else
  runs, or a disk copy a cut-off attempt left running, is waited for (``machines.tasks.wait_idle``); only a disk
  copy of Slipway's own is ever cancelled, and only in Remove (D24).
* A ready VM is never made again (M3): a gone one answers the lost text.
* The private host key leaves the VM's settings and Slipway's database right after the pin (E9). A pair that
  can't be read any more is made again only where no VM can hold the old one (E1).
* Every stage change goes through ``machines.set_stage`` (Decision 6). Errors are ``MachineError`` with Slipway's
  own sentence, never ESXi's text or the password.

The waits below are module attributes, counted in polls of ``ctx.sleep``, so a test with a no-op sleep doesn't
wait.
"""

from __future__ import annotations

import math
from collections import Counter
from collections.abc import AsyncIterator, Awaitable, Callable
from contextlib import asynccontextmanager, suppress
from typing import Any, ClassVar

from sqlalchemy import select, update

from slipway.db.session import get_sessionmaker, session_scope
from slipway.models import MachineSnapshot, MachineStage, ProviderAccount, Resource, SnapshotMode
from slipway.services import cloudinit, esxi, machines, resources, tls_pin, vmnet
from slipway.services.machines import Busy, Ensured, MachineContext, MachineState, ResizePlan, SnapshotView
from slipway.services.vmtypes import Blocker, Check, MachineError

HOW = "generated by Slipway"
ON, OFF = "poweredOn", "poweredOff"
POWER_WORDS = {ON: "running", OFF: "stopped", "suspended": "suspended"}

# Waits, in seconds; each is counted in polls of ``ctx.sleep``.
POLL = 5.0
ADDRESS_WAIT = 300.0  # VMware Tools reports the static address (E-R3, E7)
SHUTDOWN_WAIT = 300.0  # a clean shutdown for a resize (§8.3 step 2)
LATE_GRACE = 15.0  # after a snapshot task failed, before the snapshots are listed (§8.5)


def _polls(limit: float) -> int:
    return max(1, math.ceil(limit / POLL)) if POLL > 0 else max(1, int(limit))


def _minutes(seconds: float) -> str:
    minutes = max(1, math.ceil(seconds / 60))
    return f"{minutes} minute" if minutes == 1 else f"{minutes} minutes"


def applied_of(info: esxi.VmInfo | None) -> dict[str, int] | None:
    """``{cores, memory_mb, disk_gb}`` of a VM with exactly one disk, or None."""
    if info is None or len(info.disks) != 1 or info.cores is None or info.memory_mb is None:
        return None
    return {"cores": int(info.cores), "memory_mb": int(info.memory_mb), "disk_gb": int(info.disks[0].size_gb)}


class ApiHostMoved(MachineError):
    """The account points at another ESXi host than the one the VM was made on."""


class EsxiProvider:
    """The ``MachineProvider`` for a standalone ESXi host (§6.1)."""

    name: ClassVar[str] = "esxi"
    label: ClassVar[str] = "ESXi"

    # ------------------------------------------------------------------------------------ account side

    def clean_config(self, config: dict[str, Any], secret: str | None) -> dict[str, Any]:
        return esxi.clean_config(config, secret)

    async def test(self, account: ProviderAccount) -> list[Check]:
        """Not used for accounts (Decision 34): the accounts service calls ``esxi.run_test`` itself."""
        return await esxi.run_test(account)

    def freeze(self, account: ProviderAccount, network: dict[str, Any]) -> dict[str, Any]:
        """``machines.spec`` at create: where the VM goes, frozen from the account and its network (§3.2)."""
        config = account.config or {}
        return {
            "api_host": self._host_of(config.get("url")), "datastore": config.get("datastore"),
            "resource_pool": config.get("resource_pool") or esxi.DEFAULT_RESOURCE_POOL,
            "source_vm": config.get("source_vm"), "port_group": network.get("port_group"),
        }

    # ------------------------------------------------------------------------------------------ plumbing

    @staticmethod
    def _host_of(url: Any) -> str | None:
        try:
            return tls_pin.url_host_port(str(url or ""))[0].lower()
        except tls_pin.TlsPinError:
            return None

    def _api_host_problem(self, ctx: MachineContext) -> str | None:
        """§8.2: the VM was made on ``spec.api_host``; an account pointing elsewhere touches nothing."""
        frozen = str((ctx.machine.spec or {}).get("api_host") or "").lower()
        now = self._host_of((ctx.account.config or {}).get("url"))
        if frozen and now and frozen != now:
            return f"{ctx.vm} was made on {frozen}, but the account now points at {now}; Slipway changed nothing"
        return None

    @asynccontextmanager
    async def _session(self, ctx: MachineContext, *, purpose: str = "job") -> AsyncIterator[esxi.EsxiApi]:
        problem = self._api_host_problem(ctx)
        if problem:
            raise ApiHostMoved(problem)
        if ctx.account.secret:
            ctx.hide.add(ctx.account.secret)
        if ctx.machine.host_key_private:
            ctx.hide.add(ctx.machine.host_key_private)
        async with esxi.session(ctx.account, purpose=purpose) as api:
            yield api

    def _read_purpose(self, ctx: MachineContext) -> str:
        return "job" if ctx.deployment_id is not None else "read"

    @staticmethod
    def _uuid(ctx: MachineContext) -> str | None:
        value = (ctx.machine.ids or {}).get("instance_uuid")
        return str(value) if value else None

    def _spec(self, ctx: MachineContext, key: str) -> str:
        return str((ctx.machine.spec or {}).get(key) or "")

    def _ours(self, ctx: MachineContext, info: esxi.VmInfo) -> bool:
        """The name is the machine's and both markers name this machine and this environment (D20)."""
        return (info.name == ctx.vm and info.owner == str(ctx.machine.id)
                and info.environment == str(ctx.env.id))

    def _marked(self, ctx: MachineContext, info: esxi.VmInfo | None) -> bool:
        """A VM carrying this machine's or this environment's marker."""
        return info is not None and (info.owner == str(ctx.machine.id) or info.environment == str(ctx.env.id))

    def _not_ours_text(self, ctx: MachineContext) -> str:
        return (f"The VM Slipway recorded for {ctx.env.name} isn't {ctx.vm} with its marker any more; Slipway "
                "changed nothing")

    def _disk_of(self, ctx: MachineContext, info: esxi.VmInfo) -> str:
        """The disk Slipway copies for the VM: ``<vm>-disk0.vmdk`` in the VM's own folder (E5)."""
        return esxi.normalize_path(f"{info.folder}/{esxi.disk_file(ctx.vm)}")

    def _disk_problem(self, ctx: MachineContext, info: esxi.VmInfo, *, none_ok: bool = False) -> str | None:
        """E-R2: exactly one disk, the one Slipway copied (any snapshot deltas above it)."""
        if not info.disks:
            return None if none_ok else f"{ctx.vm} has no disk"
        if len(info.disks) != 1 or esxi.normalize_path(info.disks[0].base) != self._disk_of(ctx, info):
            return f"{ctx.vm} has a disk Slipway didn't put there"
        return None

    async def _task(self, ctx: MachineContext, call: Callable[..., Awaitable[Any]], *args: Any, **kw: Any) -> Any:
        """Run an ``EsxiApi`` call that starts a task: the task goes to ``last_task`` (own transaction) before
        the client waits on it, and is cleared when it ends. A task Slipway stopped waiting for stays in
        ``last_task`` (it may still run, D24), unless it was a copy Slipway cancelled."""
        started = False

        async def on_task(ref: esxi.TaskRef) -> None:
            nonlocal started
            started = True
            await machines.tasks.started(ctx, ref.id, ref.kind)

        try:
            result = await call(*args, on_task=on_task, **kw)
        except esxi.TaskTimedOut as exc:
            if started and exc.cancelled:
                await machines.tasks.ended(ctx)
            raise
        except MachineError:
            if started:
                await machines.tasks.ended(ctx)
            raise
        if started:
            await machines.tasks.ended(ctx)
        return result

    async def _running(self, ctx: MachineContext, api: esxi.EsxiApi, *, skip_own_copy: bool = False) -> list[Busy]:
        """Tasks queued or running on the VM, anyone's (§6.8), read from the VM's list and the host's.

        The host-wide list is the only place a disk copy shows (it runs on no VM, A5 deviation 3): the copy
        Slipway recorded in ``last_task`` always counts, and while the VM isn't ready any copy with no VM does
        (a cut-off attempt's)."""
        vm, uuid = ctx.vm, self._uuid(ctx)
        refs: list[esxi.TaskRef] = []
        if uuid:
            with suppress(esxi.VmGone):
                refs.extend(await api.running_tasks(uuid))
        last = (ctx.machine.last_task or {}).get("id")
        building = ctx.machine.stage != MachineStage.READY
        for ref in await api.running_tasks(None):
            if ref.entity == vm or (last and ref.id == last) or (building and ref.is_copy and not ref.entity):
                refs.append(ref)
        out: list[Busy] = []
        seen: set[str] = set()
        for ref in refs:
            if ref.id in seen:
                continue
            seen.add(ref.id)
            if skip_own_copy and ref.is_copy and ref.id == last and ref.cancelable:
                continue
            out.append(Busy(kind=ref.words if ref.kind in esxi.TASK_WORDS else ref.kind, where=ref.entity or vm,
                            started_at=ref.started_at, task_id=ref.id))
        return out

    async def running(self, ctx: MachineContext) -> list[Busy]:
        async with self._session(ctx, purpose=self._read_purpose(ctx)) as api:
            return await self._running(ctx, api)

    async def _wait_idle(self, ctx: MachineContext, api: esxi.EsxiApi, *, skip_own_copy: bool = False) -> None:
        await machines.tasks.wait_idle(ctx, read=lambda: self._running(ctx, api, skip_own_copy=skip_own_copy))

    async def _wait_power(self, ctx: MachineContext, api: esxi.EsxiApi, uuid: str, state: str, limit: float) -> bool:
        tries = _polls(limit)
        for attempt in range(tries):
            info = await api.find_vm(uuid)
            if info is not None and info.power == state:
                return True
            if attempt + 1 < tries:
                await ctx.sleep(POLL)
        return False

    async def _power_on(self, ctx: MachineContext, api: esxi.EsxiApi, uuid: str) -> None:
        await self._wait_idle(ctx, api)
        await ctx.say(f"Powering on {ctx.vm}")
        await self._task(ctx, api.power_on, uuid)

    async def _wait_address(self, ctx: MachineContext, api: esxi.EsxiApi, uuid: str, *, made: bool) -> str | None:
        """E-R3, E7: VMware Tools reports the VM's static address within 5 minutes (real vNICs only). Another
        address only is the cloud-init text. Tools that never answer are a warning for a made VM (SSH is the real
        check) and an error for a new one. Returns the warning, if any."""
        address = ctx.machine.network["address"]
        seen: list[str] = []
        answered = False
        tries = _polls(ADDRESS_WAIT)
        for attempt in range(tries):
            view = await api.guest(uuid)
            if view.tools_running and view.ipv4:
                answered = True
                if address in view.ipv4:
                    return None
                seen = list(view.ipv4)
            if attempt + 1 < tries:
                await ctx.sleep(POLL)
        if answered:
            raise MachineError(f"{ctx.vm} came up at {', '.join(seen)}, not {address}. Check the seed VM's cloud-init "
                               "and the network's settings")
        if made:
            note = f"VMware Tools on {ctx.vm} didn't answer in {_minutes(ADDRESS_WAIT)}; carrying on over SSH"
            await ctx.say(note)
            return note
        raise MachineError(f"VMware Tools on {ctx.vm} didn't report an address in {_minutes(ADDRESS_WAIT)}. Check "
                           "that the seed VM has open-vm-tools installed")

    async def _made_vm(self, ctx: MachineContext, api: esxi.EsxiApi, *, disks: bool = True) -> esxi.VmInfo:
        """E-R1 (and E-R2 with ``disks``): the made VM is there and Slipway's. Raises with nothing changed."""
        uuid = self._uuid(ctx)
        if uuid is None:
            raise MachineError(f"Slipway never made {ctx.vm}")
        info = await api.find_vm(uuid)
        if info is None:
            text = machines.lost_text(ctx.machine, env=ctx.env)
            other = await api.find_vm_by_name(ctx.vm)
            if self._marked(ctx, other):
                text += (f". {ctx.vm} carries this environment's marker but isn't the VM Slipway recorded; remove it "
                         "by hand")
            raise MachineError(text)
        if not self._ours(ctx, info):
            raise MachineError(self._not_ours_text(ctx))
        if disks:
            problem = self._disk_problem(ctx, info)
            if problem:
                raise MachineError(f"{problem}; Slipway changed nothing")
        return info

    async def _vm_rows(self, ctx: MachineContext) -> list[Resource]:
        async with get_sessionmaker()() as db:
            rows = await db.scalars(select(Resource).where(
                Resource.provider == ctx.machine.provider, Resource.kind == machines.VM_KIND,
                Resource.provider_id.startswith(f"{ctx.machine.account_id}:"),
            ))
            return [r for r in rows if (r.details or {}).get("machine_id") == str(ctx.machine.id)]

    async def _forget_vm(self, ctx: MachineContext, *, why: str, summary: str) -> None:
        """The recorded VM is gone or goes: its ``vm`` row forgotten and the ids cleared, audited
        ``machine.rebuild``, so the next ``record_vm`` doesn't meet the old row (E2)."""
        old = self._uuid(ctx)
        actor = await machines._user(ctx.user_id)
        for row in await self._vm_rows(ctx):
            await resources.forget(row.id, actor=actor)
        await machines.write(ctx, ids={}, audit_action="machine.rebuild", summary=summary,
                             details={"name": ctx.vm, "old": old, "why": why})

    async def _record(self, ctx: MachineContext, info: esxi.VmInfo) -> None:
        await machines.record_vm(
            ctx.machine, info.uuid, {"moref": info.moref}, user_id=ctx.user_id,
            ids={"instance_uuid": info.uuid, "moref": info.moref, "vm_path": info.path},
        )

    # --------------------------------------------------------------------------------------------- ensure

    async def ensure(self, ctx: MachineContext) -> Ensured:
        """Make, continue or check the VM (§8.2); never resizes and never stops a made VM."""
        async with self._session(ctx) as api:
            if ctx.machine.stage == MachineStage.READY:
                return await self._ensure_ready(ctx, api)
            return await self._ensure_new(ctx, api)

    async def _ensure_ready(self, ctx: MachineContext, api: esxi.EsxiApi) -> Ensured:
        info = await self._made_vm(ctx, api)  # E-R1, E-R2
        if info.power != ON:  # E-R3
            await self._power_on(ctx, api, info.uuid)
        warnings: list[str] = []
        warning = await self._wait_address(ctx, api, info.uuid, made=True)
        if warning:
            warnings.append(warning)
        expected = ctx.host.host_key or ctx.machine.host_key_public or ""
        return Ensured(address=ctx.machine.network["address"], expected_key=expected, how=HOW, reread_key=None,
                       warnings=warnings)  # E-R4

    def _pinned(self, ctx: MachineContext) -> bool:
        """The host is pinned to the VM's key already (an earlier attempt pinned it, then stopped)."""
        return bool(ctx.host.host_key) and machines._same_key(ctx.host.host_key, ctx.machine.host_key_public)

    async def _ensure_new(self, ctx: MachineContext, api: esxi.EsxiApi) -> Ensured:
        """Stage planned, creating or booting: E1-E8."""
        info = await self._locate(ctx, api)  # E2, E3
        info = await self._host_key(ctx, api, info)  # E1
        if info is None:
            info = await self._create(ctx, api)  # E4
        info = await self._disk(ctx, api, info)  # E5
        if ctx.machine.stage != MachineStage.BOOTING:  # E6: written before the power-on
            await machines.set_stage(ctx, MachineStage.BOOTING.value)
        await self._power_on(ctx, api, info.uuid)
        await self._wait_address(ctx, api, info.uuid, made=False)  # E7
        if self._pinned(ctx):  # pinned by an attempt that stopped before its scrub (E9)
            current = await api.find_vm(info.uuid)
            if ctx.machine.host_key_private or (current is not None and "guestinfo.userdata" in current.guestinfo_keys):
                await self._scrub(ctx, api, info.uuid)
        return Ensured(address=ctx.machine.network["address"], expected_key=ctx.machine.host_key_public or "",
                       how=HOW, reread_key=None)  # E8: the driver pins

    async def _locate(self, ctx: MachineContext, api: esxi.EsxiApi) -> esxi.VmInfo | None:
        """E2 and E3: the recorded VM, or one an earlier attempt made but didn't record (adopted by its markers).
        Refusals change nothing."""
        vm = ctx.vm
        uuid = self._uuid(ctx)
        if uuid:
            info = await api.find_vm(uuid)
            if info is not None:
                if not self._ours(ctx, info):
                    raise MachineError(self._not_ours_text(ctx))
                return info
            await ctx.say(f"The half-made {vm} is gone from ESXi; making it again")
            await self._forget_vm(ctx, why="gone before it was ready",
                                  summary=f"The half-made {vm} ({uuid}) is gone from ESXi; making it again")
        named = await api.find_vm_by_name(vm)
        if named is None:
            return None
        if not self._ours(ctx, named):
            raise MachineError(f"ESXi already has a VM named {vm} that isn't this environment's. Slipway changed "
                               "nothing: rename or remove it, or recreate the environment")
        await self._record(ctx, named)
        await machines.write(ctx, audit_action="machine.adopt", summary=f"Found {vm} from an earlier attempt",
                             details={"name": vm, "ids": {"instance_uuid": named.uuid, "moref": named.moref}})
        await ctx.say(f"Found {vm} from an earlier attempt")
        return named

    async def _new_key(self, ctx: MachineContext) -> None:
        private, public = machines._host_key_pair(ctx.vm)
        ctx.hide.add(private)
        await machines.write(ctx, host_key_private=private, host_key_public=public)

    async def _host_key(self, ctx: MachineContext, api: esxi.EsxiApi, info: esxi.VmInfo | None) -> esxi.VmInfo | None:
        """E1: a host key pair that is missing, or can't be read with the current SLIPWAY_ENCRYPTION_KEY, is made
        again only where no VM can hold the old one. A readable pair is never replaced. Returns the VM to go on
        with, or None when there is none (any more)."""
        machine, vm = ctx.machine, ctx.vm
        if machine.host_key_private and machine.host_key_public:
            return info
        if info is not None and self._pinned(ctx):
            return info  # the VM presents the pinned key: the private half isn't needed any more
        if info is None:
            if ctx.host.host_key:
                await machines.unpin(ctx, f"{vm} is made again with a new host key")
            await self._new_key(ctx)
            await ctx.say(f"Made a new host key for {vm}")
            return None
        if machine.stage == MachineStage.BOOTING:  # it may have booted and installed the old key (D9)
            await ctx.say(f"{vm}'s host key can't be read any more and the VM may have booted with it; making {vm} "
                          "again")
            await self._remove_vm(ctx, api, info)
            await self._forget_vm(ctx, why="its host key couldn't be read after it may have booted",
                                  summary=f"Removed the half-made {vm} ({info.uuid}): its host key couldn't be read")
            if ctx.host.host_key:
                await machines.unpin(ctx, f"{vm} is made again with a new host key")
            await self._new_key(ctx)
            return None
        # Never powered on (booting is written before the power-on): the new pair goes into its settings.
        await self._new_key(ctx)
        await self._wait_idle(ctx, api)
        await self._task(ctx, api.set_extra_config, info.uuid, self._guestinfo(ctx))
        await ctx.say(f"Made a new host key for {vm} and wrote it into its cloud-init settings")
        return info

    def _guestinfo(self, ctx: MachineContext) -> dict[str, str]:
        """``guestinfo.metadata`` and ``.userdata`` (§8.4): the static address and the slipway user with its
        sudo, Slipway's client key and the generated host key pair."""
        machine, net = ctx.machine, ctx.machine.network
        try:
            meta = cloudinit.metadata(machine.id, machine.name, f"{net['address']}/{net['prefix']}", net["gateway"],
                                      list(net.get("dns_servers") or []))
            user = cloudinit.userdata(machine.name, ctx.host.public_key or "", machine.host_key_private or "",
                                      machine.host_key_public or "")
        except (KeyError, ValueError) as exc:
            raise MachineError(f"Slipway can't write {ctx.vm}'s cloud-init settings: {exc}") from None
        return cloudinit.guestinfo(meta, user)

    async def _check_guest_ips(self, ctx: MachineContext, api: esxi.EsxiApi) -> None:
        address = ctx.machine.network["address"]
        for name, ips in sorted((await api.guest_ips()).items()):
            if name != ctx.vm and address in ips:
                raise MachineError(f"{name} on ESXi already reports {address}, so Slipway won't give that address to "
                                   f"{ctx.vm}. Slipway changed nothing")

    async def _delete_loose_disk(self, ctx: MachineContext, api: esxi.EsxiApi, path: str) -> None:
        """Delete Slipway's own disk file from an earlier attempt, only when no VM has it attached."""
        users = await api.disk_users(path)
        if users:
            raise MachineError(f"{path} is attached to {', '.join(users)}, so Slipway won't delete it")
        await self._task(ctx, api.delete_disk, path)
        await ctx.say(f"Deleted {path}, left by an earlier attempt")

    async def _clean_folder(self, ctx: MachineContext, api: esxi.EsxiApi, folder: str) -> None:
        """E4: Slipway's own disk in ``[<datastore>] <vm>/`` is deleted when no VM uses it; any other file
        refuses (else ESXi would put the new VM in ``<vm>_1/`` and the old files would stay for good)."""
        names = await api.list_folder(folder)
        if not names:
            return
        disk = esxi.disk_file(ctx.vm)
        mine = {disk, disk[:-5] + "-flat.vmdk"} if disk in names else set()
        others = sorted(n for n in names if n not in mine)
        if others:
            raise MachineError(f"{folder}/ already holds files no VM uses ({', '.join(others)}). Slipway changed "
                               "nothing: remove them in the ESXi Host Client, then retry")
        if mine:
            await self._delete_loose_disk(ctx, api, f"{folder}/{disk}")

    async def _create(self, ctx: MachineContext, api: esxi.EsxiApi) -> esxi.VmInfo:
        """E4: the address checked once more (registry, guest IPs, probe), the folder cleaned, then the VM made
        with both markers and its guestinfo, and its ids recorded at once."""
        machine, vm = ctx.machine, ctx.vm
        await machines.check_address_free(ctx, probe=False)
        await self._check_guest_ips(ctx, api)
        await machines.probe_address(ctx)
        await self._wait_idle(ctx, api)  # a copy from a cut-off attempt may still be writing into the folder
        datastore = self._spec(ctx, "datastore")
        await self._clean_folder(ctx, api, esxi.vm_folder(datastore, vm))
        size = vmnet.check_size(machine.size)
        spec = esxi.VmSpec(
            name=vm, datastore=datastore, resource_pool=self._spec(ctx, "resource_pool") or esxi.DEFAULT_RESOURCE_POOL,
            port_group=self._spec(ctx, "port_group"), cores=size["cores"], memory_mb=size["memory_mb"],
            annotation=(f"Made by Slipway for {ctx.env.name}'s {machine.slot} slot. Remove it from Slipway, not by "
                        "hand."),
            owner=esxi.owner_keys(machine.id, ctx.env.id), guestinfo=self._guestinfo(ctx),
        )
        if machine.stage != MachineStage.CREATING:
            await machines.set_stage(ctx, MachineStage.CREATING.value)
        await ctx.say(f"Making {vm} on {ctx.account.name}")
        info = await self._task(ctx, api.create_vm, spec)
        await self._record(ctx, info)
        await machines.write(ctx, audit_action="machine.create", summary=f"Made {vm} on {ctx.account.name}",
                             details={"name": vm, "ids": {"instance_uuid": info.uuid, "moref": info.moref},
                                      "datastore": datastore})
        return info

    async def _seed(self, ctx: MachineContext, api: esxi.EsxiApi) -> esxi.VmInfo:
        """The seed VM, checked again before its disk is copied: there, off, one disk, no snapshots."""
        name = self._spec(ctx, "source_vm")
        check = await esxi._seed_check(api, name)
        if not check.ok:
            raise MachineError(check.text)
        seed = await api.find_vm_by_name(name)
        if seed is None or len(seed.disks) != 1:
            raise MachineError(f"ESXi has no VM named {name} to copy the disk from")
        return seed

    async def _disk(self, ctx: MachineContext, api: esxi.EsxiApi, info: esxi.VmInfo) -> esxi.VmInfo:
        """E5: the seed's disk copied in thin, attached and grown; a copy a cut-off attempt left running is
        waited for, and the half-copied file it left is deleted only when no VM has it attached."""
        vm = ctx.vm
        await self._wait_idle(ctx, api)
        current = await api.find_vm(info.uuid)
        if current is None:
            raise MachineError(f"The half-made {vm} went from ESXi while Slipway was making it; retry")
        info = current
        if not info.disks:
            path = self._disk_of(ctx, info)
            if await api.file_exists(path):
                await self._delete_loose_disk(ctx, api, path)
            seed = await self._seed(ctx, api)
            await ctx.say(f"Copying {seed.name}'s disk to {path}")
            await self._task(ctx, api.copy_disk, seed.disks[0].path, path)
            await self._task(ctx, api.attach_disk, info.uuid, path)
            info = await api.find_vm(info.uuid) or info
        problem = self._disk_problem(ctx, info)
        if problem:
            raise MachineError(f"{problem}; Slipway changed nothing")
        wanted = vmnet.check_size(ctx.machine.size)["disk_gb"]
        if info.disks[0].size_gb < wanted:
            await ctx.say(f"Growing {vm}'s disk to {wanted} GB")
            await self._task(ctx, api.grow_disk, info.uuid, wanted)
            info = await api.find_vm(info.uuid) or info
        return info

    async def _scrub(self, ctx: MachineContext, api: esxi.EsxiApi, uuid: str) -> None:
        await self._wait_idle(ctx, api)
        await self._task(ctx, api.set_extra_config, uuid, cloudinit.scrub())
        await machines.write(ctx, host_key_private=None)
        await ctx.say(f"Removed the cloud-init user-data, with its host key, from {ctx.vm}'s settings")

    async def after_pin(self, ctx: MachineContext) -> None:
        """E9: the user-data (the private host key with it) leaves the VM's settings, and the private half
        leaves Slipway's database. ESXi may still hold a copy in vmware.log (docs/machines.md)."""
        uuid = self._uuid(ctx)
        if uuid is None:
            return
        async with self._session(ctx) as api:
            await self._scrub(ctx, api, uuid)

    # ------------------------------------------------------------------------------------------- describe

    async def _recorded_snapshots(self, ctx: MachineContext) -> set[str]:
        async with get_sessionmaker()() as db:
            return set(await db.scalars(
                select(MachineSnapshot.name).where(MachineSnapshot.machine_id == ctx.machine.id,
                                                   MachineSnapshot.status != "missing")
            ))

    async def describe(self, ctx: MachineContext) -> MachineState:
        """What ESXi has for the VM now (reads only). ESXi's snapshot mode is always ``any``."""
        uuid = self._uuid(ctx)
        if uuid is None:
            return MachineState(exists=False, ours=False, why_not_ours=f"Slipway never made {ctx.vm}")
        async with self._session(ctx, purpose=self._read_purpose(ctx)) as api:
            info = await api.find_vm(uuid)
            if info is None:
                why = f"{ctx.vm} is gone from {ctx.account.name}"
                if self._marked(ctx, await api.find_vm_by_name(ctx.vm)):
                    why += f"; {ctx.vm} carries this environment's marker but isn't the VM Slipway recorded"
                return MachineState(exists=False, ours=False, why_not_ours=why)
            power = POWER_WORDS.get(info.power, info.power or None)
            if not self._ours(ctx, info):
                return MachineState(exists=True, ours=False, why_not_ours=self._not_ours_text(ctx), power=power)
            problem = self._disk_problem(ctx, info, none_ok=ctx.machine.stage != MachineStage.READY)
            busy = await self._running(ctx, api)
            listed = await api.snapshots(uuid)
            addresses: list[str] = []
            if info.power == ON:
                with suppress(MachineError):
                    addresses = list((await api.guest(uuid)).ipv4)
        recorded = await self._recorded_snapshots(ctx)
        snapshots = [SnapshotView(name=s.name, id=str(s.id), created=s.created, ours=s.name in recorded,
                                  newest=s.current) for s in listed]
        task = busy[0] if busy else None
        busy_text = None
        if task is not None:
            when = task.started_at.strftime("%H:%M") if task.started_at else "earlier"
            busy_text = f"{task.kind} (started {when})"
        return MachineState(
            exists=True, ours=problem is None, why_not_ours=problem, power=power, busy=busy_text, addresses=addresses,
            applied=applied_of(info), snapshot_mode=SnapshotMode.ANY.value, snapshots=snapshots,
        )

    # --------------------------------------------------------------------------------------------- resize

    async def check_resize(self, ctx: MachineContext) -> ResizePlan:
        """§8.3's read-only checks: the disk only grows, the VM and its disk are Slipway's, and a disk grow
        meets no VM snapshot Slipway didn't record (nor two of one name). A grow drops Slipway's own snapshots
        and takes none first (D13); cores or memory alone take a ``pre_resize`` one when the environment has
        VM snapshots."""
        size = vmnet.check_size(ctx.machine.size)
        applied = machines._sizes(ctx.machine.applied) or size
        if size["disk_gb"] < applied["disk_gb"]:
            raise MachineError(f"{ctx.vm}'s disk can't shrink from {applied['disk_gb']} GB to {size['disk_gb']} GB")
        async with self._session(ctx) as api:
            info = await self._made_vm(ctx, api)
            listed = await api.snapshots(info.uuid)
        now = applied_of(info) or applied
        grows = size["disk_gb"] > now["disk_gb"]
        changes = [key for key in machines.SIZE_KEYS if size[key] != now[key]]
        drop: list[str] = []
        snapshot_first = False
        if grows:
            recorded = await self._recorded_snapshots(ctx)
            counts = Counter(s.name for s in listed)
            foreign = sorted({s.name for s in listed if s.name not in recorded or counts[s.name] > 1})
            if foreign:
                raise MachineError(f"ESXi can't grow a disk that has VM snapshots, and {', '.join(foreign)} aren't "
                                   "Slipway's; delete them in ESXi first")
            drop = sorted(counts)
        else:
            snapshot_first = await machines.snapshots_allowed(ctx)
        return ResizePlan(to=dict(size), snapshot_first=snapshot_first, drop_snapshots=drop, changes=changes)

    async def _drop_for_resize(self, ctx: MachineContext, api: esxi.EsxiApi, uuid: str, name: str) -> None:
        snap = await self._one_snapshot(ctx, api, uuid, name)
        await self._task(ctx, api.delete_snapshot, uuid, snap.id)
        async with session_scope() as db:
            await db.execute(update(MachineSnapshot)
                             .where(MachineSnapshot.machine_id == ctx.machine.id, MachineSnapshot.name == name)
                             .values(status="missing"))
        await machines.write(ctx, audit_action="machine.snapshot_delete",
                             summary=f"Deleted the VM snapshot {name} of {ctx.vm}: ESXi can't grow a disk with it",
                             details={"name": ctx.vm, "snapshot": name, "why": "resize"})
        await ctx.say(f"Deleted the VM snapshot {name}: ESXi can't grow a disk that has one")

    async def resize(self, ctx: MachineContext, plan: ResizePlan) -> dict[str, Any]:
        """§8.3: the ``pre_resize`` snapshot, a clean shutdown, the size, the snapshot deletes and the disk grow,
        then the power-on, the address and the pinned key checked. A failure after the shutdown, or a cancel (the
        step's limit, Slipway stopping), leaves the VM off, so the next deploy finishes the resize; the resize
        step then sets the notice (§6.7)."""
        vm = ctx.vm
        to = vmnet.check_size(plan.to)
        async with self._session(ctx) as api:
            info = await self._made_vm(ctx, api)
            uuid = info.uuid
            now = applied_of(info)
            if now == to and not plan.drop_snapshots:  # the size is there already (its record was cut off)
                await ctx.say(f"{vm} already has {vmnet.size_text(now)}; nothing to resize")
                return now
            if plan.snapshot_first:
                row = await machines.pre_resize_row(ctx)
                await ctx.say(f"Taking the VM snapshot {row.name} of {vm} before the resize")
                await self._snapshot(ctx, api, info, row)

            await self._wait_idle(ctx, api)
            if info.power != OFF:
                await ctx.say(f"Shutting {vm} down for the resize")
                await api.shutdown_guest(uuid)
                if not await self._wait_power(ctx, api, uuid, OFF, SHUTDOWN_WAIT):
                    raise MachineError(f"{vm} didn't shut down in {_minutes(SHUTDOWN_WAIT)}; Slipway left it running "
                                       "at its old size")
            try:
                await ctx.say(f"Resizing {vm} to {vmnet.size_text(to)}")
                if (info.cores, info.memory_mb) != (to["cores"], to["memory_mb"]):
                    await self._task(ctx, api.set_size, uuid, to["cores"], to["memory_mb"])
                for name in plan.drop_snapshots:
                    await self._drop_for_resize(ctx, api, uuid, name)
                if to["disk_gb"] > info.disks[0].size_gb:
                    await self._task(ctx, api.grow_disk, uuid, to["disk_gb"])
            except MachineError as exc:
                await ctx.say(exc.text)
                now = None
                with suppress(MachineError):
                    now = applied_of(await api.find_vm(uuid))
                state = vmnet.size_text(now) if now else "a size Slipway can't read"
                raise MachineError(f"Slipway left {vm} off at {state}; retry the deploy to finish the resize") from None

            await self._power_on(ctx, api, uuid)
            await self._wait_address(ctx, api, uuid, made=True)
            applied = applied_of(await api.find_vm(uuid)) or dict(to)
        await machines.check_resized(ctx)
        warnings: list[str] = []
        if applied["disk_gb"] > info.disks[0].size_gb:
            warning = await machines.growpart_warning(ctx, applied["disk_gb"])
            if warning:
                await ctx.say(warning)
                warnings.append(warning)
        return {**applied, "warnings": warnings} if warnings else applied

    # ------------------------------------------------------------------------------------------ snapshots

    async def _one_snapshot(self, ctx: MachineContext, api: esxi.EsxiApi, uuid: str, name: str) -> esxi.SnapshotInfo:
        """§8.5: a name that appears twice is never picked."""
        matches = [s for s in await api.snapshots(uuid) if s.name == name]
        if not matches:
            raise MachineError(f"{ctx.vm} has no VM snapshot named {name} on ESXi; Slipway changed nothing")
        if len(matches) > 1:
            raise MachineError(f"{ctx.vm} has {len(matches)} VM snapshots named {name} on ESXi, so Slipway won't pick "
                               "one; Slipway changed nothing")
        return matches[0]

    async def _set_row(self, row: MachineSnapshot, **fields: Any) -> None:
        async with session_scope() as db:
            stored = await db.get(MachineSnapshot, row.id, with_for_update=True)
            if stored is not None:
                for key, value in fields.items():
                    setattr(stored, key, value)
        for key, value in fields.items():
            setattr(row, key, value)

    async def _snapshot(self, ctx: MachineContext, api: esxi.EsxiApi, info: esxi.VmInfo, row: MachineSnapshot) -> bool:
        if row.machine_id != ctx.machine.id:
            raise MachineError(f"The VM snapshot {row.name} isn't {ctx.vm}'s; Slipway changed nothing")
        await self._wait_idle(ctx, api)
        description = f"Slipway {row.reason} snapshot of {ctx.vm}"
        quiesced = True
        try:
            try:
                await self._task(ctx, api.take_snapshot, info.uuid, row.name, description, memory=False, quiesce=True)
            except esxi.QuiesceFailed:
                await ctx.say("VMware Tools couldn't quiesce the file systems; taking a crash-consistent snapshot "
                              "instead")
                quiesced = False
                await self._task(ctx, api.take_snapshot, info.uuid, row.name, description, memory=False,
                                 quiesce=False)
        except MachineError as exc:
            await ctx.say(f"{exc.text.rstrip('.')}. Slipway checks again in {int(LATE_GRACE)} seconds")
            await ctx.sleep(LATE_GRACE)
            try:
                names = [s.name for s in await api.snapshots(info.uuid)]
            except MachineError:
                names = []
            if names.count(row.name) == 1:
                await self._set_row(row, status="ready", quiesced=quiesced, note="The task ended late")
                return quiesced
            await self._set_row(row, status="failed", quiesced=None)
            raise MachineError(f"ESXi didn't take the VM snapshot {row.name} of {ctx.vm}") from None
        await self._set_row(row, status="ready", quiesced=quiesced)
        return quiesced

    async def snapshot(self, ctx: MachineContext, row: MachineSnapshot) -> bool:
        """Take the VM snapshot ``row`` names (already committed ``pending``), quiesced, else crash-consistent.
        A task that fails is given 15 seconds, then the snapshot list decides: there, ``ready`` (``The task ended
        late``); not there, ``failed``. Returns whether VMware Tools quiesced the file systems."""
        async with self._session(ctx) as api:
            info = await self._made_vm(ctx, api, disks=False)
            return await self._snapshot(ctx, api, info, row)

    async def revert(self, ctx: MachineContext, row: MachineSnapshot) -> None:
        """Revert the VM to ``row`` (it is off afterwards: no memory was saved), power it on, check its
        address (§8.5)."""
        if row.machine_id != ctx.machine.id:
            raise MachineError(f"The VM snapshot {row.name} isn't {ctx.vm}'s; Slipway changed nothing")
        async with self._session(ctx) as api:
            info = await self._made_vm(ctx, api, disks=False)
            snap = await self._one_snapshot(ctx, api, info.uuid, row.name)
            await self._wait_idle(ctx, api)
            await ctx.say(f"Reverting {ctx.vm} to {row.name}")
            await self._task(ctx, api.revert_snapshot, info.uuid, snap.id)
            await self._power_on(ctx, api, info.uuid)
            await self._wait_address(ctx, api, info.uuid, made=True)

    async def drop_snapshot(self, ctx: MachineContext, row: MachineSnapshot) -> None:
        if row.machine_id != ctx.machine.id:
            raise MachineError(f"The VM snapshot {row.name} isn't {ctx.vm}'s; Slipway changed nothing")
        async with self._session(ctx) as api:
            info = await self._made_vm(ctx, api, disks=False)
            snap = await self._one_snapshot(ctx, api, info.uuid, row.name)
            await self._wait_idle(ctx, api)
            await self._task(ctx, api.delete_snapshot, info.uuid, snap.id)

    async def stop(self, ctx: MachineContext, *, timeout: int) -> None:
        """A clean shutdown, or MachineError when the VM is still on after ``timeout`` seconds."""
        async with self._session(ctx) as api:
            info = await self._made_vm(ctx, api, disks=False)
            if info.power == OFF:
                return
            await self._wait_idle(ctx, api)
            await api.shutdown_guest(info.uuid)
            if not await self._wait_power(ctx, api, info.uuid, OFF, timeout):
                raise MachineError(f"{ctx.vm} didn't shut down in {_minutes(timeout)}")

    # -------------------------------------------------------------------------------------------- destroy

    async def _target(self, ctx: MachineContext, api: esxi.EsxiApi) -> tuple[esxi.VmInfo | None, str | None]:
        """The VM Remove deletes: the recorded one, else one with this machine's markers found by name (an
        unfinished create). Returns ``(vm, why it isn't Slipway's)``."""
        uuid = self._uuid(ctx)
        if uuid:
            info = await api.find_vm(uuid)
            if info is not None:
                return (info, None) if self._ours(ctx, info) else (info, self._not_ours_text(ctx))
            other = await api.find_vm_by_name(ctx.vm)
            if self._marked(ctx, other):
                return None, (f"{ctx.vm} carries this environment's marker but isn't the VM Slipway recorded; remove "
                              "it by hand")
            return None, None
        named = await api.find_vm_by_name(ctx.vm)
        if named is not None and self._ours(ctx, named):
            return named, None
        return None, None

    async def destroy_blockers(self, ctx: MachineContext) -> list[Blocker]:
        """Why the VM can't be removed now (§8.5, D26), reading only; [] when ``destroy`` may go. Each blocker
        is forgettable except a task still running after the wait."""
        problem = self._api_host_problem(ctx)
        if problem:
            return [Blocker(problem, True)]
        async with self._session(ctx) as api:
            info, why = await self._target(ctx, api)
            if why:
                return [Blocker(why, True)]
            if info is not None:
                disk = self._disk_problem(ctx, info, none_ok=True)
                if disk:
                    return [Blocker(disk, True)]
            try:
                await self._wait_idle(ctx, api, skip_own_copy=True)
            except MachineError as exc:
                if exc.unreachable:
                    raise
                return [Blocker(exc.text, False)]
        return []

    async def _cancel_own_copy(self, ctx: MachineContext, api: esxi.EsxiApi) -> None:
        """A disk copy Slipway started and recorded, still running, is cancelled when ESXi allows it (D24)."""
        last = (ctx.machine.last_task or {}).get("id")
        if not last:
            return
        for ref in await api.running_tasks(None):
            if ref.id == last and ref.is_copy:
                if await api.cancel_task(ref):
                    await ctx.say(f"Cancelled the disk copy {ref.id} Slipway had started for {ctx.vm}")
                    await machines.tasks.ended(ctx)
                return

    async def _remove_vm(self, ctx: MachineContext, api: esxi.EsxiApi, info: esxi.VmInfo) -> None:
        """Power off when on, delete, and check the VM is gone (``Destroy_Task`` deletes its attached disks)."""
        await self._wait_idle(ctx, api)
        if info.power != OFF:
            await self._task(ctx, api.power_off, info.uuid)
        await self._task(ctx, api.destroy, info.uuid)
        if await api.find_vm(info.uuid) is not None:
            raise MachineError(f"{ctx.vm} is still there after destroy. Remove it by hand in the ESXi Host Client, "
                               "then retry")

    async def destroy(self, ctx: MachineContext) -> list[str]:
        """Remove the VM (§8.5): by UUID, else by name with this machine's markers; Slipway's unattached disk
        first, since ``Destroy_Task`` deletes only attached ones; then the folder checked. The rows go in
        ``machines.remove`` afterwards. Idempotent."""
        vm = ctx.vm
        uuid = self._uuid(ctx)
        done: list[str] = []
        async with self._session(ctx) as api:
            info, why = await self._target(ctx, api)
            if why:
                raise MachineError(f"{why}; nothing was removed")
            await self._cancel_own_copy(ctx, api)
            await self._wait_idle(ctx, api)
            folder = info.folder if info is not None else esxi.vm_folder(self._spec(ctx, "datastore"), vm)
            disk = esxi.normalize_path(f"{folder}/{esxi.disk_file(vm)}")
            if await api.file_exists(disk) and not await api.disk_users(disk):
                await self._task(ctx, api.delete_disk, disk)
                done.append(f"Deleted {disk}, which no VM had attached")
            if info is not None:
                await ctx.say(f"Removing {vm} ({info.uuid}) from ESXi")
                await self._remove_vm(ctx, api, info)
                done.append(f"Removed {vm} ({info.uuid}) from ESXi")
            elif uuid:
                done.append(f"{vm} is already gone")
            else:
                done.append(f"Slipway never made {vm}")
            left = await api.list_folder(folder)
            if left:
                warning = (f"ESXi left {', '.join(left)} in {folder}; Slipway no longer records them: delete them in "
                           "the ESXi Host Client")
                await ctx.say(warning)
                done.append(warning)
        return done
