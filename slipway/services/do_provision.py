async def recover_prepare(db: AsyncSession, deployment: Deployment) -> list[str]:
    """What a restart does to an interrupted ``prepare`` (§15.13): nothing is cleared. A host left ``creating``
    stays ``creating`` with its host key until the next ``prepare`` resolves its pending row (adopt and pin, or
    two absent lookups and a new create). Returns the log lines saying so."""
    if deployment.environment_id is None:
        return []
    rows = await db.scalars(select(Host).where(Host.owner_environment_id == deployment.environment_id,
                                               Host.provider == PROVIDER).order_by(Host.name))
    notes = []
    for host in rows:
        if hosts.phase_of(host) == hosts.PHASE_CREATING:
            notes.append(f"{host.name} stays building with its host key: the next deploy to it finds out whether "
                         "its droplet was made")
    return notes


