async def resize_droplet(ctx: ProvisionContext) -> str | None:
    """The shared ``resize`` step for a droplet (§9.4, Decision 14): power off, resize with its disk, power on.

    Once DigitalOcean took ``power_off``, ``power_on`` runs in a ``finally`` under ``asyncio.shield``, so a
    failed resize, a cancel or the step timeout (during the power_off's wait too) still powers the droplet on
    (at its old size when the resize didn't finish). Returns a note when there was nothing to do (the slot
    became the active one of two, the size already applied, or a size that wouldn't grow, which is left
    alone).
    """
    env = await _env(ctx)
    account = await _account(ctx, env)
    instance, host, _owner = await _load(ctx, env)
    slot = str(instance.slot)
    name = do_rules.droplet_name(env.name, slot)
    wanted = (env.cloud or {}).get("droplet_size")
    applied = (host.provider_state or {}).get("size")
    if _is_active_of_two(env, instance, await _app_slots(ctx)):
        return f"{slot} is the active slot: its droplet keeps {applied} until another slot is active"
    if not wanted or applied == wanted:
        return f"{name} is already {wanted}"
    if not host.provider_id:
        raise ProvisionError(f"{name} isn't built yet: deploy to {slot} to build it")
    region = str((env.cloud or {}).get("region") or "")
    try:
        async with DigitalOceanClient(account.secret or "", redactor=ctx.redactor) as client:
            problem = do_rules.droplet_grow_problem(str(applied), str(wanted), await catalog_for(client, region))
            if problem:
                await ctx.say(f"{name} stays {applied}: {problem}")
                return f"{name} stays {applied}: {problem}"
            droplet = await client.droplet(host.provider_id)
            if droplet is None:
                raise ProvisionError(f"{name} is gone from DigitalOcean: deploy to {slot} to build it again")
            await ctx.say(f"Resizing {name} to {wanted}: it stops for a few minutes")
            # From the power_off on, the droplet is powered on again whatever happens (shielded): an action
            # DigitalOcean already took (the power_off, then the resize) keeps it busy, so that is waited for
            # first. ``inflight`` names the step reached and the id of the action DigitalOcean took.
            inflight: dict[str, Any] = {}
            try:
                if droplet.get("status") != "off":
                    await _power_off(client, str(host.provider_id), name, inflight)
                inflight.clear()
                inflight["kind"] = "resize"
                await _action(client, host.provider_id, "resize", RESIZE_WAIT, f"Resizing {name}", ctx.say,
                              started=inflight, size=wanted, disk=True)
                await _resized(ctx, host.id, name, wanted)
            except BaseException:
                await _power_on_after(ctx, client, host.id, str(host.provider_id), name, wanted, inflight)
                raise
            try:
                await _shielded(_power_on(client, str(host.provider_id), name, ctx.say))
            except DigitalOceanError as exc:
                raise ProvisionError(f"{name} may still be powered off: Slipway couldn't power it on ({exc}). "
                                     "Deploy to its slot again") from None
            async with ctx.db() as db:
                host = await db.get(Host, host.id)
            run = _Run(ctx, env, account, client, instance, host, slot)
            stack, _remote = await _pinned_session(run, name, seconds=PIN_WAIT)
            await stack.aclose()
    except (DigitalOceanError, do_rules.DoRuleError) as exc:
        raise step_error(account.name, exc) from None
    await ctx.say(f"{name} is now {wanted}")
    return None


async def _resized(ctx: ProvisionContext, host_id: uuid.UUID, name: str, size: str) -> None:
    await _save_host(ctx, host_id, phase=hosts.PHASE_READY, state={"size": size})
    rows = [r for r in await _rows(ctx, "droplet") if r.name == name]
    if rows:
        await resources.update_details(rows[0].id, size=size)


async def _power_off(client: DigitalOceanClient, droplet_id: str, name: str, inflight: dict[str, Any]) -> None:
    """The resize's ``power_off``. Its POST is shielded, so the action's id is noted in ``inflight`` the moment
    DigitalOcean took it, even under a cancel; the wait for it is not (``_power_on_after`` finishes it)."""
    inflight["kind"] = "power_off"

    async def send() -> dict[str, Any]:
        action = await client.droplet_action(droplet_id, "power_off")
        inflight["id"] = action["id"]
        return action

    action = await _shielded(send())
    done = await _finish(client, droplet_id, action["id"], POWER_WAIT, f"Powering off {name}")
    if done.get("status") != "completed":
        raise ProvisionError(f"Powering off {name} failed: DigitalOcean's action ended {done.get('status')}")


async def _power_on_after(ctx: ProvisionContext, client: DigitalOceanClient, host_id: uuid.UUID, droplet_id: str,
                          name: str, size: str, inflight: Mapping[str, Any]) -> None:
    """Power the droplet on after a resize that failed or was cancelled, shielded from the cancel. An action
    DigitalOcean took is waited for first (the droplet takes no other action meanwhile): a resize's size is
    recorded when it finished; after a power_off that was cut or failed, the droplet is powered on only when it
    reads off. Its own failure is only logged, so the first failure is the one the step reports."""
    action_id = inflight.get("id")

    async def finish_then_power_on() -> None:
        if inflight.get("kind") == "power_off":
            if action_id is not None:
                await _finish(client, droplet_id, action_id, POWER_WAIT, f"Powering off {name}")
            droplet = await client.droplet(droplet_id)
            if droplet is None or droplet.get("status") != "off":
                return
        elif action_id is not None:
            done = await _finish(client, droplet_id, action_id, RESIZE_WAIT, f"Resizing {name}")
            if done.get("status") == "completed":
                await _resized(ctx, host_id, name, size)
        await _power_on(client, droplet_id, name, ctx.say)

    try:
        await _shielded(finish_then_power_on())
    except asyncio.CancelledError:
        raise
    except Exception as exc:  # noqa: BLE001 - the resize's own failure is the one to report
        await ctx.say(f"{name} may still be powered off: Slipway couldn't power it on ({exc}). Deploy to its slot "
                      "again")


