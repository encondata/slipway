async def database(ctx: ProvisionContext) -> Databased | None:
    """The ``database`` step (§10.1-§10.2): the cluster, made once in its trusted-sources lock, online, its
    trusted sources put back when they drifted, grown only upward, then the app's role and database made as
    ``doadmin`` on the deploying slot's droplet. The doadmin password, the CA and the SQL go on stdin, never in
    the command line or the log; the role's password is set as its SCRAM verifier, never the secret.

    None when the manifest has no managed PostgreSQL need (nothing to make).
    """
    env = await _env(ctx)
    account = await _account(ctx, env)
    man = _need_manifest(ctx, "database")
    need = postgres_need(man)
    if need is None:
        await ctx.say("slipway.yml asks for no managed database")
        return None
    instance, host, owner = await _load(ctx, env)
    try:
        async with DigitalOceanClient(account.secret or "", redactor=ctx.redactor) as client:
            env = await team_check(ctx, client, env, account)
            tagged = await client.databases_tagged(do_rules.env_tag(env.id))
            # Two clusters of one name with both tags, or one with the env tag alone: stop before any write.
            do_rules.pick_tagged(tagged, do_rules.database_name(env.name), env.id, "database")
            cluster, row_id, made_obj = await _ensure_cluster(ctx, client, env, owner, tagged)
            name = do_rules.database_name(env.name)
            cluster = await _wait_online(client, str(cluster["id"]), name)
            await _trusted_sources(ctx, client, env, account, str(cluster["id"]), name)
            notes: list[str] = []
            cluster = await _grow_cluster(ctx, client, env, account, cluster, row_id, notes)
            conn = cluster.get("private_connection") or {}
            db_host, db_port = str(conn.get("host") or ""), int(conn.get("port") or 0)
            password = await _admin_password(ctx, cluster, made_obj, row_id, name)
            ca = await client.database_ca(str(cluster["id"]))
            if ca is None:
                raise ProvisionError(f"Database cluster {name} disappeared from DigitalOcean while Slipway set it up")
            await resources.update_details(row_id, host=db_host, port=db_port, version=cluster.get("version"),
                                           size=cluster.get("size"), nodes=cluster.get("num_nodes"), ca_b64=ca)
            await _setup_role(ctx, env, man, need, host, cluster, db_host, db_port, password, ca)
            # The secret the role's password now is (a name, not a value): a later deploy to the idle slot keeps
            # it while this one is live (P4 §10.1 step 7).
            await resources.update_details(row_id, role_secret=man.data.managed.password_secret(need))
            return Databased(database_id=str(cluster["id"]), host=db_host, port=db_port,
                             created=made_obj is not None, notes=notes)
    except _STEP_ERRORS as exc:
        raise step_error(account.name, exc) from None


async def _ensure_cluster(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment, owner: Instance | None,
                          tagged: list[dict[str, Any]]) -> tuple[dict[str, Any], uuid.UUID, dict[str, Any] | None]:
    """§10.1 steps 1-2: the recorded cluster (a gone one made again only when the data owner never held data, or
    with ``rebuild_data``), a lost create adopted, else a new one. Returns the cluster, its row and, when this
    run made it, the create's answer (which carries doadmin's password)."""
    name = do_rules.database_name(env.name)
    rebuild = False
    for row in await _rows(ctx, "database"):
        live = await client.database(row.provider_id)
        if live is None:
            if holds_data(env, owner) and not await _rebuild_data(ctx):
                raise ProvisionError(
                    f"{env.name}'s database cluster is gone from DigitalOcean, and its data with it. Slipway won't "
                    "make an empty one by itself: retry with \"Make it again, empty\" (the environment's name typed), then "
                    "restore a backup")
            await resources.forget(row.id, actor=ctx.actor)
            await ctx.say(f"Database cluster {row.name} is gone from DigitalOcean; making it again, empty")
            rebuild = True
            continue
        if not do_rules.tagged_matches(live, name, env.id):
            raise ProvisionError(f"Database cluster {row.name} ({row.provider_id}) no longer carries Slipway's name "
                                 f"and tags for {env.name}. {CHANGED_NOTHING}")
        return live, row.id, None
    async with ctx.db() as db:
        kept = [r for r in await resources.pending(db, env.id, PROVIDER, "database") if r.name == name]
    stray = next((d for d in tagged if d.get("name") == name and do_rules.has_both_tags(d, env.id)), None)
    if stray is not None and not kept:
        raise ProvisionError(f"Database cluster {name} ({stray.get('id')}) carries {env.name}'s tags, but Slipway has "
                             f"no record of making it. {CHANGED_NOTHING}")
    vpcs = await _rows(ctx, "vpc")
    if not vpcs:
        raise ProvisionError(f"{env.name} has no VPC yet, so its database cluster can't be made: retry the deploy "
                             "(prepare makes the VPC)")
    cloud = env.cloud or {}
    droplet_ids = await _source_droplets(ctx)
    spec = database_spec(client, env, region=str(cloud.get("region") or ""), size=str(cloud.get("db_size")),
                         nodes=int(cloud.get("db_nodes") or 1), version=str(cloud.get("db_version")),
                         vpc_uuid=vpcs[0].provider_id, droplet_ids=droplet_ids, rebuild=rebuild)
    made = await create_once(ctx, client, spec)
    if rebuild:
        await _note_rebuild(ctx, "database")
    return made.obj, made.row_id, (None if made.adopted else made.obj)


async def _wait_online(client: DigitalOceanClient, db_id: str, name: str) -> dict[str, Any]:
    return await digitalocean.poll(lambda: client.database(db_id), lambda d: d.get("status") == "online",
                                   DB_ONLINE_WAIT, f"Database cluster {name}")


async def _source_droplets(ctx: ProvisionContext) -> list[str]:
    """The recorded droplets the cluster lets in: every one but those whose host was found ``gone``."""
    async with ctx.db() as db:
        gone = {str(h.id) for h in await db.scalars(select(Host).where(Host.owner_environment_id == ctx.environment_id))
                if hosts.phase_of(h) == hosts.PHASE_GONE}
    return [r.provider_id for r in await _rows(ctx, "droplet") if str((r.details or {}).get("host_id")) not in gone]


async def _trusted_sources(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment,
                           account: ProviderAccount, db_id: str, name: str) -> bool:
    """§10.1 step 4 and §10.2: the cluster's trusted sources are exactly the environment's recorded droplets.
    A drifted set is put back; "not ready" (409, 422) is tried again for up to 10 minutes. With no droplet
    recorded nothing is written (an empty list would let every address in). True when it wrote. A droplet found
    gone (its host ``gone``, ``_other_gone``) is left out: DigitalOcean refuses an unknown droplet (422)."""
    ids = await _source_droplets(ctx)
    live = await client.database_firewall(db_id)
    if live is None:
        raise ProvisionError(f"Database cluster {name} disappeared from DigitalOcean while Slipway set it up")
    if do_rules.database_rules_match(live, ids):
        return False
    if not ids:
        await ctx.say(f"{name}'s trusted sources stay as they are: {env.name} has no droplet now")
        return False
    rules = do_rules.database_rules(ids)
    deadline = digitalocean.monotonic() + DB_SOURCES_WAIT
    while True:
        try:
            await client.set_database_firewall(db_id, rules)
            break
        except DigitalOceanError as exc:
            if exc.status in (409, 422) and digitalocean.monotonic() + digitalocean.POLL_EVERY <= deadline:
                await digitalocean.sleep(digitalocean.POLL_EVERY)
                continue
            reason = str(step_error(account.name, exc)).rstrip(".")
            raise ProvisionError(f"{reason}. Slipway couldn't set the database's trusted sources, so it may be "
                                 "reachable from any address. Retry: Slipway sets them again before anything uses the "
                                 "database") from None
    await ctx.say(f"Set {name}'s trusted sources to {env.name}'s droplets ({', '.join(sorted(ids))})")
    return True


async def _grow_cluster(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment, account: ProviderAccount,
                        cluster: dict[str, Any], row_id: uuid.UUID, notes: list[str]) -> dict[str, Any]:
    """§10.1 step 5: the version must be the one the environment was made for; a bigger size or a standby node is
    applied once the cluster is online, never the reverse."""
    cloud = env.cloud or {}
    name = do_rules.database_name(env.name)
    version, wanted_version = str(cluster.get("version")), str(cloud.get("db_version"))
    if cloud.get("db_version") and version != wanted_version:
        raise ProvisionError(f"{name} runs PostgreSQL {version}, but {env.name} was made for {wanted_version}. "
                             "Slipway changed nothing")
    size, nodes = str(cluster.get("size")), int(cluster.get("num_nodes") or 1)
    want_size, want_nodes = str(cloud.get("db_size") or size), int(cloud.get("db_nodes") or nodes)
    if (want_size, want_nodes) == (size, nodes):
        return cluster
    problem = do_rules.database_grow_problem(size, nodes, want_size, want_nodes,
                                             await catalog_for(client, str(cloud.get("region") or "")))
    if problem:
        note = f"{name} stays {size} × {nodes}: {problem}"
        await ctx.say(note)
        notes.append(note)
        return cluster
    db_id = str(cluster["id"])
    await ctx.say(f"Growing {name} from {size} × {nodes} to {want_size} × {want_nodes}")
    await client.resize_database(db_id, want_size, want_nodes)
    deadline = digitalocean.monotonic() + DB_LEAVE_WAIT
    while True:  # a grow takes the cluster out of online first; one that finished at once may never show it
        live = await client.database(db_id)
        if live is None:
            raise ProvisionError(f"Database cluster {name} disappeared from DigitalOcean while Slipway grew it")
        if live.get("status") != "online" or digitalocean.monotonic() + digitalocean.POLL_EVERY > deadline:
            break
        await digitalocean.sleep(digitalocean.POLL_EVERY)
    cluster = await _wait_online(client, db_id, name)
    await resources.update_details(row_id, size=cluster.get("size"), nodes=cluster.get("num_nodes"))
    await _trusted_sources(ctx, client, env, account, db_id, name)
    notes.append(f"{name} is now {cluster.get('size')} × {cluster.get('num_nodes')}")
    return cluster


async def _admin_password(ctx: ProvisionContext, cluster: dict[str, Any], made: dict[str, Any] | None,
                          row_id: uuid.UUID, name: str) -> str:
    """doadmin's password (§10.1 step 6): the cluster's answer, else the create's, else the stored one. Stored
    again when it changed, and hidden from the log."""
    async with ctx.db() as db:
        row = await db.get(Resource, row_id)
    stored = ((row.credentials or {}).get("admin_password") if row is not None else None) or None
    password = ((cluster.get("connection") or {}).get("password")
                or ((made or {}).get("connection") or {}).get("password") or stored)
    if not password:
        raise ProvisionError(f"DigitalOcean didn't give doadmin's password for {name}, and Slipway has none stored. "
                             "Reset doadmin's password in DigitalOcean, then retry")
    ctx.redactor.add(str(password))
    if password != stored:
        await resources.set_credentials(row_id, {"admin_password": str(password)})
    return str(password)


async def _setup_role(ctx: ProvisionContext, env: Environment, man: manifest.Manifest, need: str, host: Host,
                      cluster: dict[str, Any], db_host: str, db_port: int, password: str, ca: str) -> None:
    """§10.1 step 7: the role and database, as doadmin, through ``postgres:<version>-alpine`` on the slot's
    droplet. The password, the CA and the SQL are stdin; the role's password is its SCRAM verifier."""
    assert man.data.managed is not None
    spec = man.data.managed.needs[need]
    secret_key = man.data.managed.password_secret(need)
    secret = (ctx.secrets if ctx.secrets is not None else (env.app_secrets or {})).get(secret_key)
    if not secret:
        raise ProvisionError(f"{env.name} has no value for its secret {secret_key}, which data.managed.{need}.password "
                             "names. Slipway changed nothing")
    ctx.redactor.add(secret)
    verifier = do_rules.scram_sha256(secret)
    ctx.redactor.add(verifier)
    for part in verifier.split("$")[1:]:  # the parts on their own, in case one is printed alone
        ctx.redactor.add(part)
    version = str((env.cloud or {}).get("db_version") or cluster.get("version"))
    command = do_rules.psql_command(host=db_host, port=db_port, version=version)
    sql = do_rules.setup_sql(str(spec.get("user")), str(spec.get("database")), verifier=verifier)
    stdin = do_rules.psql_stdin(admin_password=password, ca_b64=ca, sql=sql)
    async with ctx.db() as db:
        fresh = await db.get(Host, host.id)
