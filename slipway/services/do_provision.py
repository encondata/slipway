def _cert_view(cert: Mapping[str, Any]) -> dict[str, Any]:
    return {"id": str(cert.get("id")), "name": cert.get("name"), "not_after": cert.get("not_after"),
            "names": certs.dns_names(cert)}


def _kept_details(row: Resource) -> dict[str, Any]:
    """A kept certificate's names and expiry: its details, or read from its leaf (a crash between the two
    commits of a fresh issue leaves the details without them)."""
    details = dict(row.details or {})
    leaf = (row.credentials or {}).get("leaf")
    if (not details.get("dns_names") or not details.get("not_after")) and leaf:
        with contextlib.suppress(Exception):
            details["dns_names"] = acme.certificate_names(str(leaf))
            details["not_after"] = acme.certificate_not_after(str(leaf)).isoformat()
    return details


def _stamped_name(env: Environment, taken: Iterable[str]) -> str:
    """``slipway-<env>-<UTC yyyymmddhhmm>``, a minute later while the name is taken (one certificate a minute)."""
    used = set(taken)
    when = wall_clock()
    name = certs.certificate_name(env.name, when)
    while name in used:
        when += timedelta(minutes=1)
        name = certs.certificate_name(env.name, when)
    return name


@dataclass
class _Certs:
    """The environment's certificates as one ``_ensure_certificate`` read them."""

    listed: list[dict[str, Any]]
    served_id: str | None
    recorded: dict[str, Resource]  # certificate id -> row


async def _record_certificate(ctx: ProvisionContext, cert: Mapping[str, Any], *, replaces: uuid.UUID | None = None,
                              rule: str) -> uuid.UUID:
    return await resources.record(
        ctx.environment_id, PROVIDER, "certificate", str(cert["id"]), str(cert["name"]), "created",
        details={"not_after": cert.get("not_after"), "dns_names": certs.dns_names(cert)}, actor=ctx.actor,
        credentials=None, audit_action="resource.adopt", replaces=replaces, rule=rule)


async def _find_certificates(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment,
                             wanted: list[str]) -> _Certs:
    """§11.2 step 2: record what is ours and unrecorded, forget what is gone."""
    listed = await client.certificates()
    by_id = {str(c.get("id")): c for c in listed}
    by_name = {str(c.get("name")): c for c in listed}
    served_id = None
    for row in await _rows(ctx, "load_balancer"):
        lb = await client.load_balancer(row.provider_id)
        served_id = do_rules.https_certificate(lb) if lb else None
    rows = await _rows(ctx, "certificate", include_pending=True)
    for row in rows:
        if resources.is_pending(row):
            cert = by_name.get(row.name)
            if cert is not None:  # an upload whose answer was lost: recorded, its kept key cleared
                await _record_certificate(ctx, cert, replaces=row.id, rule="its stamped name")
                await ctx.say(f"Found certificate {row.name}, which an earlier upload made; recorded it")
        elif row.provider_id not in by_id and await client.certificate(row.provider_id) is None:
            await resources.forget(row.id, actor=ctx.actor)
            await ctx.say(f"Certificate {row.name} is gone from DigitalOcean; Slipway forgot it")
    recorded = {r.provider_id: r for r in await _rows(ctx, "certificate")}
    hostnames = [str(h.get("hostname")) for h in env.hostnames or () if h.get("hostname")]
    for cert in listed:
        cid = str(cert.get("id"))
        if cid in recorded:
            continue
        served_ours = cid == served_id and certs.ours_for_teardown(cert, env.name, hostnames)
        if served_ours or certs.is_ours(cert, env.name, wanted):
            await _record_certificate(ctx, cert, rule="the load balancer serves it" if served_ours else "its names")
            await ctx.say(f"Recorded certificate {cert.get('name')}, which Slipway made for {env.name} before")
    recorded = {r.provider_id: r for r in await _rows(ctx, "certificate")}
    return _Certs(listed=listed, served_id=served_id, recorded=recorded)


async def _ensure_certificate(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment,
                              config: cloudflare.CloudflareConfig, wanted: list[str]) -> tuple[dict[str, Any], bool]:
    """§11.2 steps 2-4: the best recorded certificate when it has more than 30 days and exactly ``wanted``; else a
    kept one uploaded again; else a new order. Returns the certificate and whether it is new."""
    found = await _find_certificates(ctx, client, env, wanted)
    live = [c for c in found.listed if str(c.get("id")) in found.recorded]
    best = certs.best(live, found.served_id)
    when = wall_clock()
    if best is not None and not certs.needs_new(best, wanted, when):
        return dict(best), False
    # 4a: a certificate issued earlier whose upload never landed is uploaded again, never ordered again.
    for row in await _rows(ctx, "certificate", include_pending=True):
        if not resources.is_pending(row):
            continue
        details = _kept_details(row)
        if certs.kept_usable(details, wanted, when) and (row.credentials or {}).get("private_key"):
            cert = await _upload_kept(ctx, client, row, details)
            return cert, True
        await resources.forget(row.id, actor=ctx.actor)
        await ctx.say(f"Dropped the kept certificate {row.name}: "
                      + ("it has 30 days or fewer left" if certs.dns_names(details) == wanted
                         else "it covers other names than are wanted now"))
    # 4b: a new order.
    staging = bool((env.cloud or {}).get("acme_staging"))
    directory = certs.directory_url(staging=staging, production=bool(env.production), settings=get_settings())
    async with _challenge_records(ctx, config) as txt:
        issued = await certs.issue(wanted, directory=directory, keys=acme_store.AccountKeys(ctx.sessionmaker),
                                   txt=txt, say=ctx.say)
    for secret in issued.secrets():
        _add_secret_lines(ctx.redactor, secret)
    name = _stamped_name(env, [str(c.get("name")) for c in found.listed]
                         + [r.name for r in await _rows(ctx, "certificate", include_pending=True)])
    nonce = do_rules.new_nonce()
    row_id = await resources.record_pending(
        env.id, PROVIDER, "certificate", name, nonce=nonce,
        body_hash=do_rules.body_hash({"name": name, "type": "custom", "dns_names": issued.dns_names}, ()),
        credentials=issued.credentials(), actor=ctx.actor)
    await resources.update_details(row_id, **issued.details())
    await _audit(ctx, "certificate.issue", target=env,
                 summary=f"Let's Encrypt issued a certificate for {env.name} ({len(issued.dns_names)} names)",
                 details={"names": list(issued.dns_names), "not_after": issued.details()["not_after"],
                          "staging": staging, "certificate": name})
    cert = await _upload(ctx, client, row_id, name, issued.credentials(), issued.details())
    return cert, True


async def _upload_kept(ctx: ProvisionContext, client: DigitalOceanClient, row: Resource,
                       details: dict[str, Any]) -> dict[str, Any]:
    """§11.2 4a: upload a kept certificate again under its name, once two lookups 60 s apart found it absent (an
    upload whose answer was lost may still appear)."""
    info = dict((row.details or {}).get("pending") or {})
    sent_at = _parse_time(info.get("sent_at"))
    looked = [t for t in (_parse_time(x) for x in info.get("looked") or ()) if t is not None]
    deadline = digitalocean.monotonic() + PENDING_WAIT
    while True:
        cert = next((c for c in await client.certificates() if c.get("name") == row.name), None)
        if cert is not None:
            await _record_certificate(ctx, cert, replaces=row.id, rule="its stamped name")
            await ctx.say(f"Found certificate {row.name}, which an earlier upload made; recorded it")
            return dict(cert)
        at = now()
        await resources.looked(row.id, at)
        looked.append(at)
        if absent_twice(sent_at, looked):
            break
        if digitalocean.monotonic() + PENDING_POLL > deadline:
            raise ProvisionError(f"A certificate upload from {_when(sent_at)} may still appear in DigitalOcean; retry "
                                 "in a few minutes. Slipway ordered nothing new")
        await digitalocean.sleep(PENDING_POLL)
    await resources.update_details(row.id, pending={**info, "sent_at": now().isoformat(), "looked": []})
    await ctx.say(f"Uploading the kept certificate {row.name} again (no new order)")
    creds = dict(row.credentials or {})
    for secret in (creds.get("private_key"),):
        if secret:
            _add_secret_lines(ctx.redactor, str(secret))
    return await _upload(ctx, client, row.id, row.name, creds, details)


async def _upload(ctx: ProvisionContext, client: DigitalOceanClient, row_id: uuid.UUID, name: str,
                  creds: Mapping[str, Any], details: Mapping[str, Any]) -> dict[str, Any]:
    """§11.2 4c: ``POST /certificates`` and the record in the pending row's place (its kept key cleared), both
    shielded from a cancel. A failure keeps the pending row and its key for the next run."""
    body: dict[str, Any] = {"name": name, "type": "custom", "private_key": creds["private_key"],
                            "leaf_certificate": creds["leaf"]}
    if creds.get("chain"):
        body["certificate_chain"] = creds["chain"]

    async def send_and_record() -> dict[str, Any]:
        cert = await client.create_certificate(body)
        await resources.record(
            ctx.environment_id, PROVIDER, "certificate", str(cert["id"]), name, "created",
            details={"not_after": cert.get("not_after") or details.get("not_after"),
                     "dns_names": certs.dns_names(cert) or list(details.get("dns_names") or [])},
            actor=ctx.actor, credentials=None, replaces=row_id)
        return cert

    cert = await _shielded(send_and_record())
    await ctx.say(f"Uploaded certificate {name}")
    return dict(cert)


async def _set_certificate(ctx: ProvisionContext, cert: Mapping[str, Any]) -> Environment:
    return await _set_cloud(ctx, certificate=_cert_view(cert))


async def _delete_old_certificates(ctx: ProvisionContext, client: DigitalOceanClient, served: str,
                                   wanted: list[str]) -> list[str]:
    """§11.3: our certificates other than the served one go, but for one that still covers exactly ``wanted``
    with more than 30 days left; one still "in use" is left for the next run. Returns the names deleted."""
    gone = []
    when = wall_clock()
    live = {str(c.get("id")): c for c in await client.certificates()}
    for row in await _rows(ctx, "certificate"):
        if row.provider_id == served or certs.kept_usable(live.get(row.provider_id) or row.details or {}, wanted, when):
            continue
        try:
            await client.delete_certificate(row.provider_id)
        except digitalocean.Forbidden as exc:
            if exc.in_use:
                await ctx.say(f"Certificate {row.name} is still in use; the next run deletes it")
                continue
            raise
        await resources.forget(row.id, deleted=True, actor=ctx.actor)
        gone.append(row.name)
    if gone:
        await ctx.say(f"Deleted the old certificate{'s' if len(gone) != 1 else ''} {', '.join(gone)}")
    return gone


