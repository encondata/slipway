"""Slipway's DigitalOcean provisioner: the objects an environment owns, made once and checked every run.

The pipeline calls this (phase 4 §9-§11, §14.3); nothing here knows about steps or the job runner. A job
builds a ``ProvisionContext`` and calls ``prepare`` (the team, the VPC, the cloud firewall, the bucket and its
key, then the deploying slot's droplet up to a pinned, ready host), later ``resize_droplet`` (the shared
``resize`` step), ``database`` (the cluster, its trusted sources, the app's role and database) and ``edge`` (the
certificate, the load balancer, the firewall's load balancer rule). ``slot_values`` gives a slot's plan its managed
data and edge values. Remove slot calls ``remove_droplet``, the ``certificate`` job ``renew`` and teardown's
``cloud`` step ``destroy`` (find, ``check_all``, then delete). ``recover_prepare`` is what a restart does to an
interrupted ``prepare``.

Every create goes through ``create_once`` (§6.4): it looks for a create whose answer was lost before it sends
anything, checks the confirmed plan (``plan_check``, §12.3), commits a pending ``resources`` row, sends the
create with the row's nonce in it, and records the answer in the pending row's place in one commit, the
send and the record shielded from a cancel. A lost answer is found by its nonce or its name and adopted
(``resource.adopt``); a Spaces key found that way is deleted and made again, since its secret was shown
once. A create is never sent while a pending row for the same object is kept.

What every function here keeps to (J4, J13): only a 404 means gone; a 401, a 403 or any other error on a
read stops the step and forgets nothing. An object that no longer carries Slipway's marks, or that is in
the way, stops the step before any write (``Slipway changed nothing``). The droplet's private host key
exists only in the create's user-data: it is never stored or logged (D4).
"""

