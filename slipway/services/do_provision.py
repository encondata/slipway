async def read_manifest_at(ctx: ProvisionContext, read_manifest: Callable[[], Awaitable[str]],
                           env: Environment) -> manifest.Manifest:
    """slipway.yml at the resolved commit, parsed and hashed into ``options.manifest_sha256``, with the refusals
    of §14.3 checked before any DigitalOcean write: the ``digitalocean`` capability, and the values frozen in
    ``cloud`` (``edge.port``, ``edge.health``, ``data.managed.db.version``)."""
    text = await read_manifest()
    digest = hashlib.sha256(text.encode()).hexdigest()
    try:
        man = manifest.parse(text)
    except manifest.ManifestError as exc:
        raise ProvisionError(str(exc)) from None
    dep = await _deployment(ctx)
    sha7 = ((dep.commit_sha if dep else None) or "This release")[:7]
    if "digitalocean" not in man.capabilities():
        raise ProvisionError(f"{sha7}'s slipway.yml can't run on DigitalOcean: it needs edge, data.attach and "
                             "data.managed for every attach need. Slipway changed nothing")
    cloud = env.cloud or {}
    frozen = cloud.get("edge") or None
    if frozen and man.edge is not None:
        if int(frozen.get("port") or 0) != man.edge.port:
            raise ProvisionError(
                f"{sha7} changes edge.port from {frozen.get('port')} to {man.edge.port}, but {env.name}'s load "
                f"balancer and firewall were made for {frozen.get('port')}: a new port needs a new environment. "
                "Slipway changed nothing")
        if frozen.get("health") != man.edge.health:
            raise ProvisionError(
                f"{sha7} changes edge.health from {frozen.get('health')} to {man.edge.health}, but {env.name}'s "
                f"load balancer was made for {frozen.get('health')}: a new health path needs a new environment. "
                "Slipway changed nothing")
    version = cloud.get("db_version")
    need = postgres_need(man)
    if version and need is not None:
        wanted = str(man.data.managed.needs[need].get("version"))
        if wanted != str(version):
            raise ProvisionError(
                f"{sha7} changes data.managed.{need}.version from {version} to {wanted}, but {env.name}'s database "
                f"cluster was made for {version}: a new version needs a new environment. Slipway changed nothing")
    ctx.manifest, ctx.manifest_sha256 = man, digest
    await _set_options(ctx, manifest_sha256=digest)
    return man


def postgres_need(man: manifest.Manifest) -> str | None:
    """The managed need that is the PostgreSQL database (``db`` in ServerSherpa's slipway.yml)."""
    if man.data.attach is None or man.data.managed is None:
        return None
    return next((n for n, kind in man.data.attach.needs.items() if kind == "postgres" and n in man.data.managed.needs),
                None)


def objects_need(man: manifest.Manifest) -> str | None:
    """The managed need that is the bucket (``objects``)."""
    if man.data.attach is None or man.data.managed is None:
        return None
    return next((n for n, kind in man.data.attach.needs.items() if kind == "s3" and n in man.data.managed.needs), None)


def cors_hostnames(man: manifest.Manifest, env: Environment) -> list[str]:
    """The hostnames of ``data.managed.<objects>.cors``'s services, from the routes the environment planned."""
    need = objects_need(man)
    if need is None:
        return []
    services = set(man.data.managed.needs[need].get("cors") or ())
    return sorted({str(r.get("hostname")) for r in env.hostnames or () if r.get("service") in services
                   and r.get("hostname")})


async def _load(ctx: ProvisionContext, env: Environment) -> tuple[Instance, Host, Instance | None]:
    if ctx.instance_id is None:
        raise ProvisionError("prepare needs the deploying slot")
    async with ctx.db() as db:
        instance = await db.get(Instance, ctx.instance_id)
        if instance is None or instance.environment_id != env.id or instance.slot not in do_rules.SLOTS:
            raise ProvisionError("The deploying slot isn't one of the environment's app slots")
        host = await db.get(Host, instance.host_id) if instance.host_id else None
        if host is None or host.provider != PROVIDER or not hosts.owned_by(env, host):
            raise ProvisionError(f"{env.name}'s {instance.slot} slot has no droplet host Slipway made")
        owner = await db.scalar(select(Instance).where(Instance.environment_id == env.id, Instance.slot == "data"))
        return instance, host, owner


async def team_check(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment,
                     account: ProviderAccount) -> Environment:
    """D3, J9: the team the token answers for, frozen by the first DigitalOcean step; another one writes
    nothing."""
    team = provider_accounts.team_of(await client.account())
    if env.provider_team and env.provider_team != team["id"]:
        built = ((account.config or {}).get("team") or {})
        name = built.get("name") if built.get("id") == env.provider_team else env.provider_team
        raise ProvisionError(f"{account.name}'s token now answers for team {team['name']}, but {env.name} was built "
                             f"in team {name}. Slipway changed nothing: put back a token for {name}, then retry")
    if env.provider_team:
        return env

    def freeze(row: Environment) -> None:
        row.provider_team = team["id"]
    env = await _update_env(ctx, freeze)
    async with ctx.db() as db:
        row = await db.get(ProviderAccount, account.id, with_for_update=True)
        if row is not None and not (row.config or {}).get("team"):
            row.config = {**(row.config or {}), "team": team}
            await db.commit()
    await _audit(ctx, "environment.team_frozen", target=env,
                 summary=f"{env.name} is frozen on DigitalOcean team {team['name']}",
                 details={"team_id": team["id"], "team_name": team["name"], "account": account.name})
    await ctx.say(f"{env.name} is frozen on team {team['name']}")
    return env


async def _survey_droplets(run: _Run) -> list[dict[str, Any]]:
    """The environment's tagged droplets, read once before any write, so a droplet carrying the env tag
    without ``slipway`` or two droplets of one name stop the step before anything changes (§6.2, test 72).
    Another slot's recorded droplet that DigitalOcean no longer has marks that slot's host ``gone``
    (``_other_gone``)."""
    tagged = await run.client.droplets_tagged(do_rules.env_tag(run.env.id))
    for slot in do_rules.SLOTS:
        do_rules.pick_tagged(tagged, do_rules.droplet_name(run.env.name, slot), run.env.id, "droplet")
    await _other_gone(run, tagged)
    return tagged


async def _other_gone(run: _Run, tagged: list[dict[str, Any]]) -> None:
    """P4 §10.4, D28: another app slot whose recorded droplet is gone from DigitalOcean (deleted by hand) can't
    run anything, so its host becomes ``gone`` (not built): the data runner then passes it over, and a deploy
    to that slot builds it again (its own ``prepare`` forgets the row and makes a new droplet). Only a droplet
    missing from the tag listing is read, and only a 404 on its own GET counts. Nothing is written to
    DigitalOcean."""
    ctx, env = run.ctx, run.env
    listed = {str(d.get("id")) for d in tagged}
    own = do_rules.droplet_name(env.name, run.slot)
    for row in await _rows(ctx, "droplet"):
        if row.name == own or str(row.provider_id) in listed:
            continue
        if await run.client.droplet(row.provider_id) is not None:
            continue
        async with ctx.db() as db:
            inst = await mark_gone(db, env, row)
            if inst is None:
                continue
            await db.commit()
        await run.say(gone_text(row.name, str(inst.slot)))


def gone_text(droplet: str, slot: str) -> str:
    return f"Droplet {droplet} is gone from DigitalOcean: deploy to {slot} to build it again"


async def mark_gone(db: AsyncSession, env: Environment | uuid.UUID, row: Resource) -> Instance | None:
    """``_other_gone``'s rule for one recorded droplet whose own GET answered 404 (the caller's read): its slot's
    host becomes ``gone`` when it is the environment's own host, ``ready``, and still names that droplet (a
    host rebuilt since names a new one). Returns the slot instance it marked, or None; the caller commits (and
    audits, when it isn't a step)."""
    env_id = env if isinstance(env, uuid.UUID) else env.id
    inst = await db.scalar(select(Instance).where(Instance.environment_id == env_id,
                                                  Instance.slot == (row.details or {}).get("slot")))
    host = await db.get(Host, inst.host_id, with_for_update=True) if inst and inst.host_id else None
    if host is None or not hosts.owned_by(env_id, host) or hosts.phase_of(host) != hosts.PHASE_READY:
        return None
    if host.provider_id and str(host.provider_id) != str(row.provider_id):
        return None
    hosts.set_phase(host, hosts.PHASE_GONE)
    return inst


async def _release_gone(ctx: ProvisionContext, instance_id: uuid.UUID) -> None:
    """The slot's live release went with its gone droplet's disk (D28, P4 §15.3): it is no longer live, so the
    data runner passes it over (§10.4 rule 3 runs this deploy's backup on its new release, or rule 2 on the
    other slot) and nothing runs its commands on the new droplet. It is kept as ``app_state.gone_live`` for
    the record; the next release to go live writes ``live`` again."""
    async with ctx.db() as db:
        inst = await db.get(Instance, instance_id, with_for_update=True)
        state = dict((inst.app_state if inst is not None else None) or {})
        if inst is None or not isinstance(state.get("live"), dict):
            return
        state["gone_live"] = state.pop("live")
        inst.app_state = state
        await db.commit()


async def ensure_vpc(run: _Run) -> dict[str, Any]:
    """§11.1: the environment's VPC, recorded and marked; made when there is none."""
    ctx, env, client = run.ctx, run.env, run.client
    name = do_rules.vpc_name(env.name)
    rebuild = False
    for row in await _rows(ctx, "vpc"):
        vpc = await client.vpc(row.provider_id)
        if vpc is None:
            await resources.forget(row.id, actor=ctx.actor)
            await run.say(f"VPC {row.name} is gone from DigitalOcean; making it again")
            rebuild = True
            continue
        if vpc.get("name") != name or not do_rules.vpc_is_marked(vpc, env.id):
            raise ProvisionError(f"VPC {row.name} ({row.provider_id}) no longer carries Slipway's name and marker "
                                 f"for {env.name}. {CHANGED_NOTHING}")
        run.vpc = vpc
        break
    if run.vpc is None:
        made = await create_once(ctx, client, vpc_spec(client, env, region=run.region, rebuild=rebuild))
        if rebuild:
            await _note_rebuild(ctx, "vpc")
        run.vpc = made.obj
    if (env.cloud or {}).get("vpc_range") != run.vpc.get("ip_range"):
        run.env = env = await _set_cloud(ctx, vpc_range=run.vpc.get("ip_range"))
    return run.vpc


def wanted_firewall(env: Environment, account: ProviderAccount, lb: Resource | None) -> dict[str, Any]:
    """The firewall's whole body: the SSH rule, and the load balancer's rule once ``edge`` made it (§11.4)."""
    sources = (account.config or {}).get("ssh_sources") or []
    if not sources:
        raise ProvisionError(f"{account.name} has no SSH sources: add the address Slipway connects to droplets "
                             "from on the account, then retry. Slipway changed nothing")
    edge = (env.cloud or {}).get("edge") or {}
    if lb is not None and edge.get("port"):  # edge added it: prepare keeps it
        return do_rules.firewall_body(env.name, env.id, ssh_sources=sources, lb_id=lb.provider_id,
                                      port=int(edge["port"]))
    return do_rules.firewall_body(env.name, env.id, ssh_sources=sources)


