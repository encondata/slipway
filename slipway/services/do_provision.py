# ------------------------------------------------------------------------------------------------ helpers


def now() -> datetime:
    """The time on the DigitalOcean client's wall clock (the fake's clock in tests)."""
    return datetime.fromtimestamp(digitalocean.clock(), UTC)


def _parse_time(value: Any) -> datetime | None:
    try:
        when = datetime.fromisoformat(str(value))
    except (TypeError, ValueError):
        return None
    return when if when.tzinfo else when.replace(tzinfo=UTC)


def _when(value: datetime | None) -> str:
    return value.astimezone(UTC).strftime("%Y-%m-%d %H:%M UTC") if value else "an earlier run"


def _kind_text(kind: str) -> str:
    return {"database": "database cluster", "spaces_key": "Spaces key", "vpc": "VPC",
            "load_balancer": "load balancer"}.get(kind, kind.replace("_", " "))


def _forbidden(account: str, exc: DigitalOceanError) -> ProvisionError:
    """J13's text for a 403 that isn't about an object in use."""
    text = str(exc)
    if text.startswith("The token "):
        text = f"{account}'s token {text[len('The token '):]}"
    return ProvisionError(f"{text}. Slipway changed nothing: give the token that scope, then retry")


def step_error(account: str, exc: BaseException) -> ProvisionError:
    """Any failure of a provisioning call as the step's text: a 403 says which scope the token lacks (J13)."""
    if isinstance(exc, ProvisionError):
        return exc
    if isinstance(exc, digitalocean.Forbidden) and not exc.in_use:
        return _forbidden(account, exc)
    return ProvisionError(str(exc))


def holds_data(env: Environment, owner: Instance | None) -> bool:
    """Whether the environment's data may hold something a person would miss: it went live, or its data
    owner was ever deployed or seeded. A gone cluster or bucket is then not made again empty by itself."""
    if env.status not in ("new",):
        return True
    if owner is None:
        return False
    return bool(owner.last_deployed_at or owner.current_commit_sha or owner.seed_snapshot_id)


def _add_secret_lines(redactor: ssh.Redactor, secret: str) -> None:
    """Hide a multi-line secret (a private key) line by line, since logs are scrubbed a line at a time."""
    redactor.add(secret)
    for line in secret.splitlines():
        if line and not line.startswith("-----"):
            redactor.add(line)


async def _shielded[T](coro: Awaitable[T]) -> T:
    """Run ``coro`` to its end even when the caller is cancelled (P3's shielded cancel), then re-raise the
    cancel. Used for a create's send and record, and for powering a droplet back on."""
    task = asyncio.ensure_future(coro)
    cancelled = False
    while not task.done():
        try:
            await asyncio.shield(task)
        except asyncio.CancelledError:
            if not task.done():
                cancelled = True
        except BaseException:  # the task's own failure: read below
            break
    if cancelled:
        if not task.cancelled() and task.exception() is not None:
            log.warning("A shielded DigitalOcean call failed after its step was cancelled: %s", task.exception())
        raise asyncio.CancelledError
    return task.result()


# ----------------------------------------------------------------------------------------- database access


async def _env(ctx: ProvisionContext) -> Environment:
    async with ctx.db() as db:
        env = await db.get(Environment, ctx.environment_id)
        if env is None or env.is_deleted:
            raise ProvisionError("The environment is gone")
        if env.provider != PROVIDER:
            raise ProvisionError(f"{env.name} isn't placed on DigitalOcean")
        return env


async def _account(ctx: ProvisionContext, env: Environment) -> ProviderAccount:
    async with ctx.db() as db:
        account = await db.get(ProviderAccount, env.provider_account_id)
    if account is None or account.is_removed:
        raise ProvisionError(f"{env.name}'s DigitalOcean account was removed")
    if not account.secret:
        raise ProvisionError(f"{account.name} has no API token: enter one on the account, then retry")
    for value in provider_accounts.redactions(account):
        ctx.redactor.add(value)
    return account


async def _update_env(ctx: ProvisionContext, change: Callable[[Environment], None]) -> Environment:
    """Apply ``change`` to the environment row under a row lock and commit."""
    async with ctx.db() as db:
        env = await db.get(Environment, ctx.environment_id, with_for_update=True)
        assert env is not None
        change(env)
        await db.commit()
        return env


async def _set_cloud(ctx: ProvisionContext, **changes: Any) -> Environment:
    def change(env: Environment) -> None:
        env.cloud = {**(env.cloud or {}), **changes}
    return await _update_env(ctx, change)


async def _deployment(ctx: ProvisionContext) -> Deployment | None:
    if ctx.deployment_id is None:
        return None
    async with ctx.db() as db:
        return await db.get(Deployment, ctx.deployment_id)


async def _set_options(ctx: ProvisionContext, **options: Any) -> None:
    if ctx.deployment_id is None:
        return
    async with ctx.db() as db:
        dep = await db.get(Deployment, ctx.deployment_id, with_for_update=True)
        if dep is None:
            return
        dep.options = {**(dep.options or {}), **options}
        await db.commit()


async def _note_rebuild(ctx: ProvisionContext, kind: str) -> None:
    dep = await _deployment(ctx)
    if dep is None:
        return
    made = list((dep.options or {}).get("rebuild") or [])
    if kind not in made:
        await _set_options(ctx, rebuild=[*made, kind])


async def _rows(ctx: ProvisionContext, kind: str, *, include_pending: bool = False) -> list[Resource]:
    async with ctx.db() as db:
        return await resources.owned(db, ctx.environment_id, PROVIDER, kind, include_pending=include_pending)


async def _audit(ctx: ProvisionContext, action: str, *, target: Any, summary: str,
                 details: dict[str, Any] | None = None) -> None:
    async with ctx.db() as db:
        actor = await db.get(User, ctx.actor.id) if ctx.actor is not None else None
        audit.record(db, action, actor=actor, target=target, summary=summary, details=details or {})
        await db.commit()


# ------------------------------------------------------------------------------------------- the plan


def _plan_refusal(env: Environment, what: str, how: str) -> ProvisionError:
    return ProvisionError(f"This would make {what}, which {env.name}'s confirmed plan doesn't include: {how}. "
                          "Slipway changed nothing")


async def _live_count(db: AsyncSession, client: DigitalOceanClient, env: Environment, kind: str) -> set[str]:
    """The ids of live objects that carry the environment's tag (droplets, clusters) or its fixed name (the
    load balancer inside its VPC)."""
    if kind == "droplet":
        return {str(d["id"]) for d in await client.droplets_tagged(do_rules.env_tag(env.id))}
    if kind == "database":
        return {str(d["id"]) for d in await client.databases_tagged(do_rules.env_tag(env.id))}
    if kind == "load_balancer":
        listed = await client.load_balancers()
        vpc_ids = {r.provider_id for r in await resources.owned(db, env.id, PROVIDER, "vpc")}
        return {str(lb["id"]) for lb in listed
                if lb.get("name") == do_rules.lb_name(env.name) and (not vpc_ids or lb.get("vpc_uuid") in vpc_ids)}
    return set()


async def plan_check(
    db: AsyncSession, env: Environment, kind: str, *, client: DigitalOceanClient | None = None,
    remake: bool = False, size: str | None = None, nodes: int | None = None, name: str | None = None,
) -> None:
    """Refuse a create ``env``'s confirmed plan doesn't cover (§12.3, J2), before anything is sent.

    The count for a kind is its recorded rows, its pending rows and the live objects that carry the
    environment's tag or fixed name (with ``client``), each object counted once. A droplet beyond the plan's
    ``droplets``, a droplet or cluster of another size (or node count), a second load balancer, bucket, VPC or
    firewall fails. ``remake`` (a gone object made again) skips the count: it replaces one.
    """
    plan = (env.cloud or {}).get("plan") or {}
    if not plan:
        raise ProvisionError(f"{env.name} has no confirmed plan, so Slipway makes nothing for it. "
                             "Slipway changed nothing")
    what = f"{_kind_text(kind)} {name}" if name else f"a {_kind_text(kind)}"
    if kind == "droplet" and size is not None and size != plan.get("droplet_size"):
        raise _plan_refusal(env, f"{what} of size {size}",
                            f"the plan's droplets are {plan.get('droplet_size')}; confirm a new size first")
    if kind == "database" and ((size is not None and size != plan.get("db_size"))
                               or (nodes is not None and int(nodes) != int(plan.get("db_nodes") or 0))):
        raise _plan_refusal(env, f"{what} ({size} × {nodes})",
                            f"the plan's cluster is {plan.get('db_size')} × {plan.get('db_nodes')}; "
                            "confirm a new size first")
    limits = {"droplet": int(plan.get("droplets") or 0), "database": 1, "vpc": int(plan.get("vpc") or 1),
              "firewall": int(plan.get("firewall") or 1), "bucket": int(plan.get("bucket") or 1),
              "load_balancer": 1 if plan.get("lb_size_unit") else 0}
    if kind not in limits or remake:
        return
    # DigitalOcean first, so no database transaction is held open across the HTTP calls.
    live_ids = await _live_count(db, client, env, kind) if client is not None else set()
    rows = await resources.owned(db, env.id, PROVIDER, kind, include_pending=True)
    recorded = {r.provider_id for r in rows if not resources.is_pending(r)}
    pending = sum(1 for r in rows if resources.is_pending(r))
    live = live_ids - recorded
    count = len(recorded) + pending + len(live)
    if count + 1 <= limits[kind]:
        return
    how = {
        "droplet": f"its plan has {limits['droplet']} droplet{'s' if limits['droplet'] != 1 else ''}; "
                   "Add slot confirms a second one",
        "database": "an environment has one database cluster",
        "load_balancer": "an environment has one load balancer",
        "bucket": "an environment has one bucket",
        "vpc": "an environment has one VPC",
        "firewall": "an environment has one cloud firewall",
    }[kind]
    if live:
        how += f" (DigitalOcean already lists {', '.join(sorted(live))} with {env.name}'s tag)"
    raise _plan_refusal(env, what, how)


# ------------------------------------------------------------------------------------------ create_once


Find = Callable[[str, str], Awaitable[dict[str, Any] | None]]


@dataclass
class CreateSpec:
    """How ``create_once`` makes one object of a kind (§6.4).

    ``name`` is the object's fixed name, or a function of the nonce (Spaces keys carry it in their name).
    ``body(nonce)`` is the create body with the nonce in it; ``send(body)`` sends it and answers the object.
    ``find(nonce, name)`` looks for the object a lost answer made. ``adoptable(obj)`` says whether a found
    object may be recorded (a Spaces key never: its secret was shown once); one that may not is removed with
    ``discard(obj)`` and made again. ``stray()`` returns an unrecorded object to adopt by its fixed name (it
    raises to stop). ``before_intent(nonce, body)`` runs before the pending row is committed (the droplet's
    host key).
    """

    kind: str
    name: str | Callable[[str], str]
    body: Callable[[str], dict[str, Any]]
    send: Callable[[dict[str, Any]], Awaitable[dict[str, Any]]]
    find: Find
    ident: Callable[[dict[str, Any]], str]
    details: Callable[[dict[str, Any]], dict[str, Any]] = lambda obj: {}
    credentials: Callable[[dict[str, Any]], dict[str, Any] | None] = lambda obj: None
    tags: Callable[[dict[str, Any]], list[str] | None] = lambda obj: None
    instance_id: uuid.UUID | None = None
    find_rule: str = "its request tag"
    adoptable: Callable[[dict[str, Any]], bool] = lambda obj: True
    discard: Callable[[dict[str, Any]], Awaitable[None]] | None = None
    stray: Callable[[], Awaitable[dict[str, Any] | None]] | None = None
    stray_rule: str = "its name"
    before_intent: Callable[[str, dict[str, Any]], Awaitable[None]] | None = None
    same_pending: Callable[[Resource], bool] | None = None
    secret_fields: tuple[str, ...] = ("user_data", "private_key")
    pending_credentials: dict[str, Any] | None = None
    nothing_made: Callable[[BaseException], bool] = lambda exc: (
        isinstance(exc, DigitalOceanError) and exc.status in NOTHING_MADE)
    rebuild: bool = False  # a gone object made again: audited resource.rebuild, outside the count
    size: str | None = None
    nodes: int | None = None

    def name_for(self, nonce: str) -> str:
        return self.name(nonce) if callable(self.name) else self.name

    @property
    def label(self) -> str:
        return _kind_text(self.kind) + ("" if callable(self.name) else f" {self.name}")

    def matches(self, row: Resource) -> bool:
        if self.same_pending is not None:
            return self.same_pending(row)
        return not callable(self.name) and row.name == self.name


def absent_twice(sent_at: datetime | None, looked: Iterable[datetime]) -> bool:
    """Two lookups, both at least ``PENDING_GAP`` after the create was sent and that far apart (§6.4 step 2)."""
    start = sent_at or datetime.min.replace(tzinfo=UTC)
    counted = sorted(t for t in looked if t - start >= timedelta(seconds=PENDING_GAP))
    return len(counted) >= 2 and counted[-1] - counted[0] >= timedelta(seconds=PENDING_GAP)


async def _record(ctx: ProvisionContext, spec: CreateSpec, obj: dict[str, Any], name: str, *,
                  audit_action: str, replaces: uuid.UUID | None = None, rule: str | None = None) -> uuid.UUID:
    return await resources.record(
        ctx.environment_id, PROVIDER, spec.kind, spec.ident(obj), name, "created", details=spec.details(obj),
        instance_id=spec.instance_id, actor=ctx.actor, credentials=spec.credentials(obj), tags=spec.tags(obj),
        audit_action=audit_action, replaces=replaces, rule=rule,
    )


async def _resolve_pending(ctx: ProvisionContext, spec: CreateSpec, row: Resource) -> Made | None:
    """§6.4 steps 1-2 for one pending row: the object it stands for, recorded; or None once it is known not to
    exist (two lookups apart said absent) or was discarded. Waits, looking again, while that isn't known yet."""
    nonce = resources.nonce_of(row) or ""
    info = (row.details or {}).get("pending") or {}
    sent_at = _parse_time(info.get("sent_at"))
    looked = [t for t in (_parse_time(x) for x in info.get("looked") or ()) if t is not None]
    deadline = digitalocean.monotonic() + PENDING_WAIT
    waited = False
    while True:
        obj = await spec.find(nonce, row.name)
        if obj is not None:
            if spec.adoptable(obj):
                row_id = await _record(ctx, spec, obj, row.name, audit_action="resource.adopt", replaces=row.id,
                                       rule=spec.find_rule)
                await ctx.say(f"Found {spec.label} that an earlier create made (its answer was lost); recorded it")
                return Made(obj, row_id, adopted=True)
            if spec.discard is not None:
                await spec.discard(obj)
            await resources.forget(row.id, actor=ctx.actor)
            await ctx.say(f"Found {_kind_text(spec.kind)} {row.name} from a create whose answer was lost; "
                          "Slipway can't use it, so it was deleted and is made again")
            return None
        at = now()
        await resources.looked(row.id, at)
        looked.append(at)
        if absent_twice(sent_at, looked):
            await resources.forget(row.id, actor=ctx.actor)
            await ctx.say(f"The {_kind_text(spec.kind)} create from {_when(sent_at)} made nothing; sending it again")
            return None
        if digitalocean.monotonic() + PENDING_POLL > deadline:
            raise ProvisionError(f"A {_kind_text(spec.kind)} create from {_when(sent_at)} may still appear in "
                                 "DigitalOcean; retry in a few minutes. Slipway made nothing new")
        if not waited:
            await ctx.say(f"Waiting to see whether the {_kind_text(spec.kind)} create from {_when(sent_at)} "
                          "made anything")
            waited = True
        await digitalocean.sleep(PENDING_POLL)


async def create_once(ctx: ProvisionContext, client: DigitalOceanClient | None, spec: CreateSpec) -> Made:
    """Make one object exactly once (§6.4): look for a lost answer, check the plan, commit the intent, send,
    record. Never sends a create while a pending row for the same object is kept (J12)."""
    async with ctx.db() as db:
        pending = [r for r in await resources.pending(db, ctx.environment_id, PROVIDER, spec.kind) if spec.matches(r)]
    for row in pending:
        made = await _resolve_pending(ctx, spec, row)
        if made is not None:
            return made
    if spec.stray is not None and not callable(spec.name):
        obj = await spec.stray()
        if obj is not None:
            row_id = await _record(ctx, spec, obj, spec.name, audit_action="resource.adopt", rule=spec.stray_rule)
            await ctx.say(f"Adopted {spec.label}, which Slipway made for this environment before")
            return Made(obj, row_id, adopted=True)
    async with ctx.db() as db:
        env = await db.get(Environment, ctx.environment_id)
    assert env is not None
    async with ctx.db() as db:  # plan_check reads DigitalOcean before it opens this session's transaction
        await plan_check(db, env, spec.kind, client=client, remake=spec.rebuild, size=spec.size, nodes=spec.nodes,
                         name=None if callable(spec.name) else spec.name)
    nonce = do_rules.new_nonce()
    body = spec.body(nonce)
    name = spec.name_for(nonce)
    if spec.before_intent is not None:
        await spec.before_intent(nonce, body)
    pending_id = await resources.record_pending(
        ctx.environment_id, PROVIDER, spec.kind, name, nonce=nonce,
        body_hash=do_rules.body_hash(body, spec.secret_fields), instance_id=spec.instance_id,
        credentials=spec.pending_credentials, actor=ctx.actor,
    )

    async def send_and_record() -> tuple[dict[str, Any], uuid.UUID]:
        try:
            obj = await spec.send(body)
        except Exception as exc:
            if spec.nothing_made(exc):
                await resources.forget(pending_id, actor=ctx.actor)
            raise
        row_id = await _record(ctx, spec, obj, name, audit_action="resource.rebuild" if spec.rebuild
                               else "resource.create", replaces=pending_id)
        return obj, row_id

    obj, row_id = await _shielded(send_and_record())
    await ctx.say(f"Made {_kind_text(spec.kind)} {name}")
    return Made(obj, row_id, rebuilt=spec.rebuild)


