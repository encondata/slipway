async def _save_host(ctx: ProvisionContext, host_id: uuid.UUID, *, phase: str | None = None,
                     state: dict[str, Any] | None = None, **fields: Any) -> Host:
    async with ctx.db() as db:
        host = await db.get(Host, host_id, with_for_update=True)
        assert host is not None
        for key, value in fields.items():
            setattr(host, key, value)
        if phase is not None:
            hosts.set_phase(host, phase, **(state or {}))
        await db.commit()
        return host


async def _power_on(client: DigitalOceanClient, droplet_id: str, name: str, say: Say) -> None:
    await _action(client, droplet_id, "power_on", POWER_WAIT, f"Powering on {name}", say)


async def _action(client: DigitalOceanClient, droplet_id: str, kind: str, seconds: float, what: str, say: Say,
                  *, started: dict[str, Any] | None = None, **params: Any) -> dict[str, Any]:
    """One droplet action, polled until it completes; an errored one fails. ``started`` gets the action's id the
    moment DigitalOcean took it, so a cancel can wait for it."""
    action = await client.droplet_action(droplet_id, kind, **params)
    if started is not None:
        started["id"] = action["id"]
    done = await _finish(client, droplet_id, action["id"], seconds, what)
    if started is not None:
        started.pop("id", None)
    if done.get("status") != "completed":
        raise ProvisionError(f"{what} failed: DigitalOcean's action ended {done.get('status')}")
    return done


async def _finish(client: DigitalOceanClient, droplet_id: str, action_id: Any, seconds: float,
                  what: str) -> dict[str, Any]:
    return await digitalocean.poll(lambda: client.get_action(droplet_id, action_id),
                                   lambda a: a.get("status") in ("completed", "errored"), seconds, what)


async def _recorded_droplet(run: _Run) -> tuple[Resource | None, dict[str, Any] | None]:
    """§9.2 step 1: the slot's recorded droplet, read; None when there is none or it is gone (then the host
    goes back to planned, its pin and address cleared)."""
    ctx, env, client = run.ctx, run.env, run.client
    name = do_rules.droplet_name(env.name, run.slot)
    for row in await _rows(ctx, "droplet"):
        if row.name != name:
            continue
        droplet = await client.droplet(row.provider_id)
        if droplet is None:
            await resources.forget(row.id, actor=ctx.actor)
            run.host = await _save_host(ctx, run.host.id, phase=hosts.PHASE_PLANNED,
                                        state={"public_ip": None, "private_ip": None, "built_at": None},
                                        host_key=None, host_key_fingerprint=None, hostname=f"{name}.invalid",
                                        provider_id=None)
            await _release_gone(ctx, run.instance.id)
            await run.say(f"Droplet {name} is gone from DigitalOcean; it is made again with a new host key")
            return None, None
        if not do_rules.tagged_matches(droplet, name, env.id):
            raise ProvisionError(f"Droplet {row.name} ({row.provider_id}) no longer carries Slipway's name and tags "
                                 f"for {env.name}. {CHANGED_NOTHING}")
        if droplet.get("status") == "off":
            await run.say(f"{name} is powered off (a resize was cut short); powering it on")
            await _power_on(client, str(droplet["id"]), name, run.say)
            droplet = await client.droplet(row.provider_id) or droplet
        return row, droplet
    return None, None


async def _make_droplet(run: _Run, tagged: list[dict[str, Any]], *, rebuild: bool) -> Made:
    """§9.2 steps 2-3: a lost create adopted (only while the host is ``creating`` with its key), else a new
    droplet whose generated host key is in ``hosts.host_key`` before the create is sent."""
    ctx, env, client = run.ctx, run.env, run.client
    name = do_rules.droplet_name(env.name, run.slot)
    keys: dict[str, str] = {}

    def body(nonce: str) -> dict[str, Any]:
        private, public = ssh.generate_keypair(f"root@{name}")
        _add_secret_lines(ctx.redactor, private)
        keys["public"] = public
        user_data = do_rules.droplet_userdata(env.name, run.slot, authorized_key=run.host.public_key or "",
                                              host_private_key=private, host_public_key=public)
        ctx.redactor.add(user_data)
        return do_rules.droplet_body(env.name, env.id, run.slot, region=run.region,
                                     size=str((env.cloud or {}).get("droplet_size")), vpc_uuid=str(run.vpc["id"]),
                                     nonce=nonce, user_data=user_data)

    async def before_intent(_nonce: str, _body: dict[str, Any]) -> None:
        public = keys["public"]
        run.host = await _save_host(ctx, run.host.id, phase=hosts.PHASE_CREATING, host_key=public,
                                    host_key_fingerprint=ssh.fingerprint(public))

    def adoptable(_droplet: dict[str, Any]) -> bool:
        # §9.2 step 2: only a host that is creating holds the key the lost create sent; without one the found
        # droplet is ours but untrustable, so it is deleted and made again.
        return hosts.phase_of(run.host) == hosts.PHASE_CREATING and bool(run.host.host_key)

    stray = next((d for d in tagged if d.get("name") == name and do_rules.has_both_tags(d, env.id)), None)
    spec = droplet_spec(client, env, run.slot, instance_id=run.instance.id, body=body, adoptable=adoptable,
                        before_intent=before_intent, rebuild=rebuild, size=str((env.cloud or {}).get("droplet_size")))
    async with ctx.db() as db:
        kept = [r for r in await resources.pending(db, env.id, PROVIDER, "droplet") if r.name == name]

    def refuse(found: Mapping[str, Any]) -> ProvisionError:
        return ProvisionError(f"Droplet {name} ({found.get('id')}) carries {env.name}'s tags, but Slipway has no "
                              f"record of making it. {CHANGED_NOTHING}")
    if stray is not None and not kept:
        raise refuse(stray)
    if kept:
        # The kept rows are resolved first; one judged absent is forgotten and a new create would follow. A
        # droplet of this name with both tags that none of them found (a lost create that showed up late) is
        # read again before that create, so the slot never gets a second droplet (§6.4).
        discarded: set[str] = set()
        discard = spec.discard

        async def discard_noted(droplet: dict[str, Any]) -> None:
            discarded.add(str(droplet.get("id")))
            if discard is not None:
                await discard(droplet)

        async def stray_again() -> dict[str, Any] | None:
            for d in await client.droplets_tagged(do_rules.env_tag(env.id)):
                if (d.get("name") == name and do_rules.has_both_tags(d, env.id)
                        and str(d.get("id")) not in discarded):
                    raise refuse(d)
            return None
        spec.discard, spec.stray = discard_noted, stray_again
    made = await create_once(ctx, client, spec)
    if rebuild:
        await _note_rebuild(ctx, "droplet")
    run.host = await _save_host(ctx, run.host.id, provider_id=str(made.obj["id"]))
    return made


async def _wait_droplet(run: _Run, droplet_id: str) -> dict[str, Any]:
    name = do_rules.droplet_name(run.env.name, run.slot)

    def ready(d: dict[str, Any]) -> bool:
        public, private = digitalocean.droplet_ips(d)
        return d.get("status") == "active" and bool(public and private)
    return await digitalocean.poll(lambda: run.client.droplet(droplet_id), ready, DROPLET_ACTIVE_WAIT,
                                   f"Droplet {name}")


async def _address_check(run: _Run, public_ip: str, droplet_name: str) -> None:
    """§9.2 step 5: no host row outside this environment may hold the droplet's address."""
    async with run.ctx.db() as db:
        holder = await hosts.address_holder(db, public_ip, except_host_id=run.host.id,
                                            except_environment_id=run.env.id)
