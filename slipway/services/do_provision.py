async def _freeze_edge(ctx: ProvisionContext, env: Environment, man: manifest.Manifest) -> Environment:
    """D15: ``cloud.edge`` = the release's ``edge.port`` and ``edge.health``, on the environment's first ``edge``."""
    if (env.cloud or {}).get("edge"):
        return env
    if man.edge is None:
        raise ProvisionError("slipway.yml has no edge, so Slipway can't put the app behind a load balancer")
    edge = {"port": man.edge.port, "health": man.edge.health}
    env = await _set_cloud(ctx, edge=edge)
    await _audit(ctx, "environment.edge_frozen", target=env,
                 summary=f"{env.name}'s load balancer serves port {edge['port']} and checks {edge['health']}",
                 details=dict(edge))
    await ctx.say(f"{env.name}'s load balancer forwards to port {edge['port']} and checks {edge['health']}; these "
                  "stay for the environment's life")
    return env


async def _wait_lb(client: DigitalOceanClient, lb_id: str, name: str, seconds: float, *,
                   ip: bool = False) -> dict[str, Any]:
    return await digitalocean.poll(lambda: client.load_balancer(lb_id),
                                   lambda lb: lb.get("status") == "active" and (not ip or bool(lb.get("ip"))),
                                   seconds, f"Load balancer {name}")


async def _put_certificate(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment, lb_id: str,
                           cert_id: str) -> dict[str, Any]:
    """One full-body PUT of the HTTPS rule's certificate, after an ``active`` wait, under do_lb's lock."""
    from slipway.services import do_lb  # registers the backend; imported late to keep the module graph flat

    name = do_rules.lb_name(env.name)
    async with do_lb.lock_for(env.id):
        live = await _wait_lb(client, lb_id, name, LB_ACTIVE_WAIT)
        if do_rules.https_certificate(live) == cert_id:
            return live
        await client.update_load_balancer(lb_id, do_rules.lb_update_body(live, certificate_id=cert_id))
        await ctx.say(f"{name} now serves certificate {cert_id}")
        return await _wait_lb(client, lb_id, name, LB_ACTIVE_WAIT)


async def _mark_stale(ctx: ProvisionContext, ip: str) -> list[str]:
    """§6.3: every app slot whose live release names another load balancer address is stale (the deploying slot
    is about to write the new one)."""
    marked = []
    async with ctx.db() as db:
        rows = list(await db.scalars(select(Instance).where(Instance.environment_id == ctx.environment_id,
                                                            Instance.slot.in_(do_rules.SLOTS))
                                     .with_for_update()))
        for inst in rows:
            if inst.id == ctx.instance_id:
                continue
            live = (inst.app_state or {}).get("live")
            if not live or not inst.current_commit_sha:
                continue
            if ((live.get("edge") or {}) if isinstance(live, dict) else {}).get("address") == ip:
                continue
            state = dict(inst.slot_state or {})
            state["stale"] = {"reason": STALE_LB, "at": now().isoformat(),
                              "deployment_id": ctx.deployment_id.hex if ctx.deployment_id else None}
            inst.slot_state = state
            marked.append(str(inst.slot))
        await db.commit()
    return marked


async def _ensure_lb(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment, vpc_id: str,
                     cert_id: str, notes: list[str]) -> dict[str, Any]:
    """§11.3: the recorded load balancer (a gone one made again, a renamed or moved one a stop), a lost create or a
    same-named one in the VPC adopted, else a new one with no targets and the HTTPS rule on the certificate."""
    edge = (env.cloud or {}).get("edge") or {}
    port, health = int(edge["port"]), str(edge["health"])
    name = do_rules.lb_name(env.name)
    lb: dict[str, Any] | None = None
    row_id: uuid.UUID | None = None
    rebuild = False
    for row in await _rows(ctx, "load_balancer"):
        live = await client.load_balancer(row.provider_id)
        if live is None:
            await resources.forget(row.id, actor=ctx.actor)
            await ctx.say(f"Load balancer {row.name} is gone from DigitalOcean; making it again")
            rebuild = True
            continue
        if not do_rules.lb_matches(live, env.name, vpc_id):
            raise ProvisionError(f"Load balancer {row.name} ({row.provider_id}) is no longer named {name} inside "
                                 f"{env.name}'s VPC. {CHANGED_NOTHING}")
        lb, row_id = live, row.id
        break
    made_new = False
    if lb is None:
        body = do_rules.lb_body(env.name, region=str((env.cloud or {}).get("region") or ""), vpc_uuid=vpc_id,
                                port=port, health=health, certificate_id=cert_id)
        made = await create_once(ctx, client, lb_spec(client, env, body, vpc_uuid=vpc_id, rebuild=rebuild))
        if rebuild:
            await _note_rebuild(ctx, "load_balancer")
        lb, row_id, made_new = made.obj, made.row_id, not made.adopted
    assert row_id is not None
    lb = await _wait_lb(client, str(lb["id"]), name, LB_READY_WAIT, ip=True)
    if not made_new and (problem := do_rules.lb_edge_problem(lb, port=port, health=health)):
        raise ProvisionError(problem)
    if do_rules.https_certificate(lb) != cert_id:
        lb = await _put_certificate(ctx, client, env, str(lb["id"]), cert_id)
    ip = str(lb.get("ip") or "")
    await resources.update_details(row_id, ip=ip, vpc_id=vpc_id, size_unit=lb.get("size_unit"))
    old_ip = (env.cloud or {}).get("lb_ip")

    def record_ip(row: Environment) -> None:
        row.cloud = {**(row.cloud or {}), "lb_ip": ip}
        traffic = dict(row.traffic or {})
        traffic["dns"] = {**(traffic.get("dns") or {}), "address": ip}
        row.traffic = traffic
    if old_ip != ip or ((env.traffic or {}).get("dns") or {}).get("address") != ip:
        await _update_env(ctx, record_ip)
    if old_ip and old_ip != ip:
        stale = await _mark_stale(ctx, ip)
        note = f"{name}'s address is now {ip} (was {old_ip})"
        if stale:
            note += f"; {', '.join(stale)} must be deployed again to use it"
        await ctx.say(note)
        notes.append(note)
    if rebuild:
        notes.append(f"{name} was made again with no targets: the active slot goes back on it at its next deploy or "
                     "a Publish")
    return lb


async def _firewall_lb_rule(ctx: ProvisionContext, client: DigitalOceanClient, account: ProviderAccount) -> None:
    """§11.4 in ``edge``: the firewall lets the load balancer reach ``edge.port`` (one PUT of the whole body); an
    SSH-rule change on the way is proven with fresh connections and put back when one fails."""
    env = await _fresh_env(ctx)
    rows = await _rows(ctx, "firewall")
    if not rows:
        raise ProvisionError(f"{env.name} has no cloud firewall yet: retry the deploy (prepare makes it)")
    live = await client.firewall(rows[0].provider_id)
    if live is None:
        raise ProvisionError(f"Cloud firewall {rows[0].name} is gone from DigitalOcean: retry the deploy (prepare "
                             "makes it again)")
    lbs = await _rows(ctx, "load_balancer")
    wanted = wanted_firewall(env, account, lbs[0] if lbs else None)
    if not do_rules.firewall_matches(live, wanted):
        await firewall_put(ctx, client, env, account, rows[0].id, rows[0].provider_id, live, wanted)


async def edge(ctx: ProvisionContext, *, deploying_routes: Iterable[Any] | None = None) -> Edged:
    """The ``edge`` step (§11.2-§11.4): ``cloud.edge`` frozen on the first run, the certificate for the union of
    the slots' names, the load balancer (made with no targets: D11) serving it, old certificates deleted, the
    firewall's load balancer rule, and ``traffic.dns.address`` = the load balancer's IP.

    ``deploying_routes`` are the deploying release's routes (its plan's); without them the environment's names
    whose service the release still runs stand in.
    """
    env = await _env(ctx)
    account = await _account(ctx, env)
    man = _need_manifest(ctx, "edge")
    try:
        async with DigitalOceanClient(account.secret or "", redactor=ctx.redactor) as client:
            env = await team_check(ctx, client, env, account)
            env = await _freeze_edge(ctx, env, man)
            vpcs = await _rows(ctx, "vpc")
            if not vpcs:
                raise ProvisionError(f"{env.name} has no VPC yet: retry the deploy (prepare makes it)")
            config = await _cloudflare(ctx)
            deploying = list(deploying_routes) if deploying_routes is not None else (
                deploying_routes_of(man, env) if ctx.instance_id is not None else None)
            wanted = await wanted_names(ctx, env, config, deploying=deploying)
            cert, issued = await _ensure_certificate(ctx, client, env, config, wanted)
            notes: list[str] = []
            lb = await _ensure_lb(ctx, client, env, vpcs[0].provider_id, str(cert["id"]), notes)
            await _set_certificate(ctx, cert)
            await _delete_old_certificates(ctx, client, str(cert["id"]), wanted)
            await _firewall_lb_rule(ctx, client, account)
            await ctx.say(f"{do_rules.lb_name(env.name)} serves {len(wanted)} name{'s' if len(wanted) != 1 else ''} "
                          f"at {lb.get('ip')}")
            return Edged(lb_id=str(lb["id"]), lb_ip=str(lb.get("ip") or ""), certificate=_cert_view(cert),
                         issued=issued, notes=notes)
    except _STEP_ERRORS as exc:
        raise step_error(account.name, exc) from None


# ------------------------------------------------------------------------------------- renew (§15.8)


async def renew(ctx: ProvisionContext, *, hold_lock: bool = True) -> str:
    """The ``certificate`` job's step (§14.3, §15.8): §11.2 steps 2-4 for the live slots' names, then the load
    balancer's HTTPS rule PUT under do_lb's lock and a re-read (a certificate that isn't ours stops, deleting
    nothing), ``cloud.certificate``, then the old certificates deleted. Returns the step's note.

    ``hold_lock=False`` when the caller already holds ``do_lb.lock_for(env.id)`` (the lock isn't reentrant)."""
    from slipway.services import do_lb

    env = await _env(ctx)
    account = await _account(ctx, env)
    try:
        async with DigitalOceanClient(account.secret or "", redactor=ctx.redactor) as client:
            env = await team_check(ctx, client, env, account)
            lbs = await _rows(ctx, "load_balancer")
            if not lbs:
                raise ProvisionError(f"{env.name} has no load balancer yet: deploy it first")
            config = await _cloudflare(ctx)
            wanted = await wanted_names(ctx, env, config, deploying=None)
            cert, issued = await _ensure_certificate(ctx, client, env, config, wanted)
            name = do_rules.lb_name(env.name)
            lb_id = lbs[0].provider_id
            async with (do_lb.lock_for(env.id) if hold_lock else contextlib.nullcontext()):
                live = await client.load_balancer(lb_id)
                if live is None:
                    raise ProvisionError(f"Load balancer {name} is gone from DigitalOcean: deploy again to make it")
                if do_rules.https_certificate(live) != str(cert["id"]):
                    live = await _wait_lb(client, lb_id, name, LB_ACTIVE_WAIT)
                    body = do_rules.lb_update_body(live, certificate_id=str(cert["id"]))
                    await client.update_load_balancer(lb_id, body)
                    await ctx.say(f"{name} now serves certificate {cert.get('name')}")
                live = await _wait_lb(client, lb_id, name, LB_ACTIVE_WAIT)
            if do_rules.https_certificate(live) != str(cert["id"]):
                raise ProvisionError(f"The load balancer serves a certificate that isn't Slipway's for {env.name}. "
                                     "Slipway deleted nothing")
            await _set_certificate(ctx, cert)
            await _delete_old_certificates(ctx, client, str(cert["id"]), wanted)
    except _STEP_ERRORS as exc:
        raise step_error(account.name, exc) from None
    expires = certs.not_after(cert)
    until = f", valid until {expires.strftime('%Y-%m-%d')}" if expires else ""
    return (f"Renewed: {cert.get('name')}{until}" if issued
            else f"{cert.get('name')} is still good{until}; nothing to renew")


# ------------------------------------------------------------------------------ remove a droplet (§9.3)


async def _owned_host(ctx: ProvisionContext, name: str) -> Host | None:
    async with ctx.db() as db:
        return await db.scalar(select(Host).where(Host.owner_environment_id == ctx.environment_id,
                                                  Host.provider == PROVIDER, Host.name == name))


async def _delete_host(ctx: ProvisionContext, host_id: uuid.UUID) -> bool:
    """Delete an owned host row, committed at once; False while an instance still runs on it."""
    from sqlalchemy import delete

    async with ctx.db() as db:
        if await db.scalar(select(Instance.id).where(Instance.host_id == host_id).limit(1)) is not None:
            return False
        await db.execute(delete(Host).where(Host.id == host_id))
        await db.commit()
        return True


async def _delete_slot_instance(ctx: ProvisionContext, slot: str) -> bool:
    from sqlalchemy import delete

    async with ctx.db() as db:
        inst = await db.scalar(select(Instance).where(Instance.environment_id == ctx.environment_id,
                                                      Instance.slot == slot))
        if inst is None:
            return False
        env = await db.get(Environment, ctx.environment_id, with_for_update=True)
        await db.execute(delete(Instance).where(Instance.id == inst.id))
        if env is not None:
            state = dict(env.traffic_state or {})
            if (state.get("last_slot_deploy") or {}).get("slot") == slot:
                state["last_slot_deploy"] = None
                env.traffic_state = state
        await db.commit()
        return True


async def _reconcile_sources(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment,
                             account: ProviderAccount) -> None:
    """§10.2: after a droplet went, the cluster's trusted sources are the droplets left."""
    for row in await _rows(ctx, "database"):
        if await client.database(row.provider_id) is None:
            continue
        await _trusted_sources(ctx, client, env, account, row.provider_id, row.name)


async def _drop_plan(ctx: ProvisionContext, client: DigitalOceanClient, account: ProviderAccount) -> str | None:
    """The last write of Remove slot (§15.6): ``cloud.plan.droplets = 1`` and ``cloud.cost`` recomputed, audited."""
    env = await _fresh_env(ctx)
    cloud = dict(env.cloud or {})
    plan = dict(cloud.get("plan") or {})
    if int(plan.get("droplets") or 1) <= 1:
        return None
    plan["droplets"] = 1
    old = dict(cloud.get("cost") or {})
    estimate = do_rules.cost(plan, await catalog_for(client, str(cloud.get("region") or "")),
                             do_rules.price_layers((account.config or {}).get("prices") or None, None))
    new_cost = {**old, **estimate.to_json()}
    before = int(old.get("total_cents") or 0)

    def change(row: Environment) -> None:
        row.cloud = {**(row.cloud or {}), "plan": plan, "cost": new_cost}
    env = await _update_env(ctx, change)
    delta = do_rules.delta_text(before, estimate.total_cents)
    await _audit(ctx, "environment.resize", target=env,
                 summary=f"{env.name}'s plan drops to one droplet ({delta})",
                 details={"from": {"droplets": 2}, "to": {"droplets": 1}, "old_cents": before,
                          "new_cents": estimate.total_cents, "delta": delta})
    return f"{env.name}'s plan is now one droplet ({delta})"


async def remove_droplet(ctx: ProvisionContext, slot: str) -> str | None:
    """Remove slot's ``slot`` step for DigitalOcean (§9.3): the droplet's marks, the droplet, its row, the cluster's
    trusted sources without it, the slot's instance row, its host row, each committed on its own and in that
    order, then the plan's drop to one droplet and the new cost, last. Driven from the slot's ``droplet`` row and
    its owned host row, so a retry sees what is left. Returns ``Already removed`` when nothing was."""
    env = await _env(ctx)
    account = await _account(ctx, env)
    name = do_rules.droplet_name(env.name, slot)
    try:
        async with DigitalOceanClient(account.secret or "", redactor=ctx.redactor) as client:
            env = await team_check(ctx, client, env, account)
            rows = [r for r in await _rows(ctx, "droplet", include_pending=True) if r.name == name]
            host = await _owned_host(ctx, name)
            async with ctx.db() as db:
                instance = await db.scalar(select(Instance.id).where(Instance.environment_id == env.id,
                                                                     Instance.slot == slot))
            if not rows and host is None and instance is None:
                await _drop_plan(ctx, client, account)
                return "Already removed"
            for row in rows:
                await _delete_droplet_row(ctx, client, env, row, name, slot)
            await _reconcile_sources(ctx, client, env, account)
            if await _delete_slot_instance(ctx, slot):
                await ctx.say(f"Removed {env.name}'s {slot} slot")
            if host is not None and await _delete_host(ctx, host.id):
                await ctx.say(f"Removed host {host.name}")
            note = await _drop_plan(ctx, client, account)
    except _STEP_ERRORS as exc:
        raise step_error(account.name, exc) from None
    return note


async def _delete_droplet_row(ctx: ProvisionContext, client: DigitalOceanClient, env: Environment, row: Resource,
                              name: str, slot: str) -> None:
    """§9.3 steps 1-3 for one row: a pending one is resolved first (a lost create is found and deleted too)."""
    if resources.is_pending(row):
        spec = droplet_spec(client, env, slot, instance_id=None, body=lambda nonce: {}, adoptable=lambda d: True)
        made = await _resolve_pending(ctx, spec, row)
        if made is None:
            return
        async with ctx.db() as db:
            found = await db.get(Resource, made.row_id)
        if found is None:
            return
        row = found
    live = await client.droplet(row.provider_id)
    if live is not None and not do_rules.tagged_matches(live, name, env.id):
        raise ProvisionError(f"Droplet {row.name} ({row.provider_id}) no longer carries Slipway's name and tags for "
                             f"{env.name}. {CHANGED_NOTHING}")
    if live is not None:
        await client.delete_droplet(row.provider_id)
        await ctx.say(f"Deleted droplet {name} ({row.provider_id})")
    await resources.forget(row.id, deleted=True, actor=ctx.actor)


# ------------------------------------------------------------------------------ teardown (§15.11)


TEARDOWN_KINDS = ("vpc", "firewall", "droplet", "database", "load_balancer", "certificate", "spaces_key", "bucket")


@dataclass
class _Teardown:
    """One ``cloud`` step: its client and the temporary full-access key it makes when it needs one."""

    ctx: ProvisionContext
    env: Environment
    account: ProviderAccount
    client: DigitalOceanClient
    setup_key: dict[str, Any] | None = None
    setup_row: uuid.UUID | None = None
    s3_clients: list[spaces.SpacesClient] = field(default_factory=list)

    @property
    def region(self) -> str:
        return str((self.env.cloud or {}).get("region") or (self.account.config or {}).get("region") or "")

    @property
    def bucket(self) -> str:
        return do_rules.bucket_name(self.env.name, self.env.id)

    async def s3(self) -> spaces.SpacesClient:
        """A Spaces client under the temporary key; a lost answer of its create is resolved and made again."""
        if self.setup_key is None:
            spec = spaces_key_spec(self.client, self.env, bucket=self.bucket, setup=True)
            try:
                made = await create_once(self.ctx, self.client, spec)
            except DigitalOceanError as exc:
                if exc.status is not None:
                    raise
                made = await create_once(self.ctx, self.client, spec)  # the pending row is resolved first
            self.setup_key, self.setup_row = made.obj, made.row_id
            self.ctx.redactor.add(made.obj.get("secret_key"))
        key = spaces.SpacesKey(str(self.setup_key["access_key"]), str(self.setup_key["secret_key"]))
        client = spaces.SpacesClient(self.region, key)
        self.s3_clients.append(client)
        return client

    async def close(self) -> None:
        for client in self.s3_clients:
            with contextlib.suppress(Exception):
                await client.aclose()
        self.s3_clients.clear()
        if self.setup_key is None:
            return
        try:
            await self.client.delete_spaces_key(str(self.setup_key["access_key"]))
        except DigitalOceanError as exc:
            await self.ctx.say(f"Couldn't delete the temporary Spaces key {self.setup_key.get('name')} ({exc}); the "
                               "next run deletes it")
            return
        if self.setup_row is not None:
            await resources.forget(self.setup_row, deleted=True, actor=self.ctx.actor)
        self.setup_key = self.setup_row = None


def _slot_of_droplet(env: Environment, name: str) -> str:
    return name.removeprefix(f"slipway-{env.name}-")


def _sweep_spec(td: _Teardown, row: Resource) -> CreateSpec:
    """How a pending row's object is looked for in teardown: the kind's own spec, every find adopted."""
    env, client = td.env, td.client
    cloud = env.cloud or {}
    if row.kind == "vpc":
        return vpc_spec(client, env, region=td.region)
    if row.kind == "firewall":
        return firewall_spec(client, env, {})
    if row.kind == "droplet":
        return droplet_spec(client, env, _slot_of_droplet(env, row.name), instance_id=None, body=lambda n: {},
                            adoptable=lambda d: True)
    if row.kind == "database":
        return database_spec(client, env, region=td.region, size=str(cloud.get("db_size")),
                             nodes=int(cloud.get("db_nodes") or 1), version=str(cloud.get("db_version")),
                             vpc_uuid="", droplet_ids=[])
    if row.kind == "load_balancer":
        spec = lb_spec(client, env, {}, vpc_uuid="")

        async def find_lb(_nonce: str, _name: str) -> dict[str, Any] | None:
            vpc_ids = {r.provider_id for r in await _rows(td.ctx, "vpc")}
            return next((lb for lb in await client.load_balancers() if lb.get("name") == row.name
                         and (not vpc_ids or lb.get("vpc_uuid") in vpc_ids)), None)
        spec.find = find_lb
        return spec
    if row.kind == "certificate":
        return certificate_spec(client, env, row.name, {}, not_after=None, dns_names=[])
    if row.kind == "spaces_key":
        return spaces_key_spec(client, env, bucket=td.bucket,
                               setup=do_rules.spaces_key_is_setup(row.name, env.name, env.id))
    if row.kind == "bucket":
        return bucket_spec(env, td.bucket, region=td.region, s3=td.s3)
    raise ProvisionError(f"Slipway doesn't know how to look for a {row.kind}")


async def _adopt(td: _Teardown, kind: str, obj: Mapping[str, Any], provider_id: str, name: str,
                 details: dict[str, Any] | None = None) -> None:
    await resources.record(td.env.id, PROVIDER, kind, provider_id, name, "created", details=details or {},
                           actor=td.ctx.actor, tags=list(obj.get("tags") or []) or None,
                           audit_action="resource.adopt", rule="teardown")
    await td.ctx.say(f"Found {_kind_text(kind)} {name} ({provider_id}), which Slipway made for {td.env.name}; it goes "
                     "too")


async def sweep(td: _Teardown) -> None:
    """§15.11 step 2 (the find): every pending row resolved (found: recorded; absent twice: dropped), then every
    unrecorded object §6.2 would adopt recorded with the rule ``teardown``. A 403 on any read stops the step
    before anything is deleted."""
    ctx, env, client = td.ctx, td.env, td.client
    for kind in TEARDOWN_KINDS:
        for row in [r for r in await _rows(ctx, kind, include_pending=True) if resources.is_pending(r)]:
            await _resolve_pending(ctx, _sweep_spec(td, row), row)

    recorded = {(r.kind, r.provider_id) for r in await _rows_all(ctx, include_pending=False)}
    prefix = f"slipway-{env.name}-"
    tag = do_rules.env_tag(env.id)
    tagged = (("droplet", await client.droplets_tagged(tag)), ("database", await client.databases_tagged(tag)))
    for kind, listed in tagged:
        for obj in listed:
            oid = str(obj.get("id"))
            if (kind, oid) in recorded:
                continue
            if not do_rules.has_both_tags(obj, env.id) or not str(obj.get("name") or "").startswith(prefix):
                await ctx.say(f"Left {_kind_text(kind)} {obj.get('name')} ({oid}): it carries {tag} but not Slipway's "
                              "other marks")
                continue
            details = _droplet_details(obj, _slot_of_droplet(env, str(obj.get("name")))) if kind == "droplet" else {}
            await _adopt(td, kind, obj, oid, str(obj.get("name")), details)

    vpc_name = do_rules.vpc_name(env.name)
    for vpc in await client.vpcs():
        if (vpc.get("name") == vpc_name and do_rules.vpc_is_marked(vpc, env.id)
                and ("vpc", str(vpc["id"])) not in recorded):
            await _adopt(td, "vpc", vpc, str(vpc["id"]), vpc_name,
                         {"region": td.region, "ip_range": vpc.get("ip_range")})
    vpc_ids = {r.provider_id for r in await _rows(ctx, "vpc")}
    lb_name = do_rules.lb_name(env.name)
    served: set[str] = set()
    for lb in await client.load_balancers():
        if lb.get("name") != lb_name or lb.get("vpc_uuid") not in vpc_ids:
            continue
        if cid := do_rules.https_certificate(lb):
            served.add(str(cid))
        if ("load_balancer", str(lb["id"])) not in recorded:
            await _adopt(td, "load_balancer", lb, str(lb["id"]), lb_name,
                         {"ip": lb.get("ip") or None, "vpc_id": lb.get("vpc_uuid"), "size_unit": lb.get("size_unit")})
    for fw in await client.firewalls():
        if do_rules.firewall_adoptable(fw, env.name, env.id) and ("firewall", str(fw["id"])) not in recorded:
            await _adopt(td, "firewall", fw, str(fw["id"]), str(fw["name"]), _firewall_details(fw))
    hostnames = [str(h.get("hostname")) for h in env.hostnames or () if h.get("hostname")]
    for cert in await client.certificates():
        if ("certificate", str(cert["id"])) in recorded or not certs.ours_for_teardown(cert, env.name, hostnames):
            continue
        await _adopt(td, "certificate", cert, str(cert["id"]), str(cert["name"]),
                     {"not_after": cert.get("not_after"), "dns_names": certs.dns_names(cert)})

    keys = await client.spaces_keys()
    key_rows = await _rows(ctx, "spaces_key")
    ours = False
    for key in keys:
        verdict = do_rules.spaces_key_verdict(key, env.name, env.id, bucket=td.bucket,
                                              recorded=[r.name for r in key_rows])
        if verdict == "stop":
            raise ProvisionError(f"Spaces key {key.get('name')} is named like {env.name}'s but has grants on other "
                                 f"buckets. {CHANGED_NOTHING}")
        if verdict == "foreign":
            continue
        ours = True
        if verdict == "delete":
            setup = do_rules.spaces_key_is_setup(str(key.get("name")), env.name, env.id)
            await _adopt(td, "spaces_key", key, str(key["access_key"]), str(key.get("name")),
                         {"bucket": td.bucket, "permission": (key.get("grants") or [{}])[0].get("permission"),
                          "role": "setup" if setup else "bucket"})
    if not await _rows(ctx, "bucket") and (ours or key_rows):
        # Evidence that a bucket step ran: a HEAD under the temporary key finds a bucket whose row was lost.
        if await (await td.s3()).bucket_exists(td.bucket):
            await _adopt(td, "bucket", {}, td.bucket, td.bucket, {"region": td.region,
                                                                  "endpoint": spaces.endpoint(td.region)})


async def check_all(td: _Teardown) -> None:
    """§15.11 step 3 (J5): every recorded object that still exists still carries Slipway's marks; the first that
    doesn't stops the step before anything is deleted."""
    ctx, env, client = td.ctx, td.env, td.client
    vpc_ids = {r.provider_id for r in await _rows(ctx, "vpc")}
    keys = None
    for row in await _rows_all(ctx, include_pending=False):
        live: dict[str, Any] | None
        ok = True
        if row.kind == "droplet":
            live = await client.droplet(row.provider_id)
            ok = live is None or do_rules.tagged_matches(live, row.name, env.id)
        elif row.kind == "database":
            live = await client.database(row.provider_id)
            ok = live is None or do_rules.tagged_matches(live, do_rules.database_name(env.name), env.id)
        elif row.kind == "vpc":
            live = await client.vpc(row.provider_id)
            ok = live is None or (live.get("name") == do_rules.vpc_name(env.name)
                                  and do_rules.vpc_is_marked(live, env.id))
        elif row.kind == "load_balancer":
            live = await client.load_balancer(row.provider_id)
            ok = live is None or (live.get("name") == do_rules.lb_name(env.name)
                                  and (not vpc_ids or live.get("vpc_uuid") in vpc_ids))
        elif row.kind == "firewall":
            live = await client.firewall(row.provider_id)
            ok = live is None or live.get("name") == do_rules.firewall_name(env.name)
        elif row.kind == "certificate":
            live = await client.certificate(row.provider_id)
            ok = live is None or bool(certs.name_pattern(env.name).match(str(live.get("name") or "")))
        elif row.kind == "spaces_key":
            if keys is None:
                keys = {str(k.get("access_key")): k for k in await client.spaces_keys()}
            live = keys.get(row.provider_id)
            ok = live is None or live.get("name") == row.name
        elif row.kind == "bucket":
            ok = row.provider_id == td.bucket
        if not ok:
            raise ProvisionError(f"{_kind_text(row.kind).capitalize()} {row.provider_id} no longer looks like "
                                 f"Slipway's {row.name}. {CHANGED_NOTHING}")


async def _delete_retrying(ctx: ProvisionContext, what: str, delete: Callable[[], Awaitable[bool]],
                           seconds: float) -> bool:
    """A delete DigitalOcean refuses while the object is still "in use" (403, 409, 422) is tried again every 10 s
    for up to ``seconds``. False when it was already gone."""
    deadline = digitalocean.monotonic() + seconds
    waited = False
    while True:
        try:
            return await delete()
        except DigitalOceanError as exc:
            busy = exc.status in (409, 422) or (exc.status == 403 and getattr(exc, "in_use", False))
            if not busy or digitalocean.monotonic() + DELETE_EVERY > deadline:
                raise
            if not waited:
                await ctx.say(f"{what} is still in use; trying again")
                waited = True
            await digitalocean.sleep(DELETE_EVERY)


def _safe(text: Any) -> str:
    import re

    return re.sub(r"[^A-Za-z0-9._:-]", "", str(text or ""))[:64] or "?"


async def _delete_vpc(td: _Teardown, row: Resource) -> None:
    """The VPC last: retried while members linger (10 min), stopped at once by a 403 with no members (a scope
    problem), and on timeout the step names up to 10 members."""
    client = td.client
    deadline = digitalocean.monotonic() + VPC_DELETE_WAIT
    while True:
        try:
            await client.delete_vpc(row.provider_id)
            break
        except DigitalOceanError as exc:
            if exc.status not in (403, 409, 422):
                raise
            members = await client.vpc_members(row.provider_id)
            if members is None:
                break
            if not members and exc.status == 403 and not exc.in_use:
                raise step_error(td.account.name, exc) from None
            if digitalocean.monotonic() + DELETE_EVERY > deadline:
                names = ", ".join(_safe(m.get("name") or m.get("urn")) for m in members[:10])
                raise ProvisionError(f"VPC {row.name} still has members after {VPC_DELETE_WAIT // 60} minutes "
                                     f"({names}), so Slipway couldn't delete it. Delete them in DigitalOcean, then "
                                     "retry") from None
            await digitalocean.sleep(DELETE_EVERY)
    await resources.forget(row.id, deleted=True, actor=td.ctx.actor)
    await td.ctx.say(f"Deleted VPC {row.name}")


async def _delete_all(td: _Teardown) -> None:
    """§15.11 step 4, in Sirdar's order, each object forgotten as it goes; the temporary key in a ``finally``."""
    ctx, env, client = td.ctx, td.env, td.client
    try:
        for row in await _rows(ctx, "load_balancer"):
            await client.delete_load_balancer(row.provider_id)
            await resources.forget(row.id, deleted=True, actor=ctx.actor)
            await ctx.say(f"Deleted load balancer {row.name}")
        for row in await _rows(ctx, "certificate"):
            await _delete_retrying(ctx, f"Certificate {row.name}",
                                   lambda r=row: client.delete_certificate(r.provider_id), CERT_DELETE_WAIT)
            await resources.forget(row.id, deleted=True, actor=ctx.actor)
            await ctx.say(f"Deleted certificate {row.name}")
        for row in await _rows(ctx, "firewall"):
            await client.delete_firewall(row.provider_id)
            await resources.forget(row.id, deleted=True, actor=ctx.actor)
            await ctx.say(f"Deleted cloud firewall {row.name}")
        for row in await _rows(ctx, "droplet"):
            await client.delete_droplet(row.provider_id)
            await resources.forget(row.id, deleted=True, actor=ctx.actor)
            await ctx.say(f"Deleted droplet {row.name} ({row.provider_id})")
            host = await _owned_host(ctx, row.name)
            if host is not None and await _delete_host(ctx, host.id):
                await ctx.say(f"Removed host {host.name}")
            await _reconcile_sources(ctx, client, env, td.account)
        for row in await _rows(ctx, "database"):
            await client.delete_database(row.provider_id)
            await resources.forget(row.id, deleted=True, actor=ctx.actor)
            await ctx.say(f"Deleted database cluster {row.name}")
        for row in await _rows(ctx, "spaces_key"):
            if row.id == td.setup_row:
                continue
            await client.delete_spaces_key(row.provider_id)
            await resources.forget(row.id, deleted=True, actor=ctx.actor)
            await ctx.say(f"Deleted Spaces key {row.name}")
        for row in await _rows(ctx, "bucket"):
            s3 = await td.s3()
            emptied = await s3.empty_bucket(row.provider_id)
            if emptied:
                await ctx.say(f"Deleted {emptied} file{'s' if emptied != 1 else ''} from bucket {row.name}")
            await s3.delete_bucket(row.provider_id)
            await resources.forget(row.id, deleted=True, actor=ctx.actor)
            await ctx.say(f"Deleted bucket {row.name}")
    finally:
        await td.close()
    for row in await _rows(ctx, "vpc"):
        await _delete_vpc(td, row)
    async with ctx.db() as db:  # planned host rows that never got a droplet
        left = list(await db.scalars(select(Host).where(Host.owner_environment_id == env.id,
                                                        Host.provider == PROVIDER)))
    for host in left:
        if await _delete_host(ctx, host.id):
            await ctx.say(f"Removed host {host.name}")


async def _leftovers(td: _Teardown) -> list[str]:
    """What is still recorded, or listed with the environment's marks, after the second find and delete."""
    env, client = td.env, td.client
    left = [f"{_kind_text(r.kind)} {r.name}" for r in await _rows_all(td.ctx)]
    tag = do_rules.env_tag(env.id)
    left += [f"droplet {d.get('name')}" for d in await client.droplets_tagged(tag) if do_rules.has_both_tags(d, env.id)]
    left += [f"database cluster {d.get('name')}" for d in await client.databases_tagged(tag)
             if do_rules.has_both_tags(d, env.id)]
    left += [f"Spaces key {k.get('name')}" for k in await client.spaces_keys()
             if do_rules.spaces_key_is_ours(str(k.get("name") or ""), env.name, env.id)]
    return sorted(set(left))


async def destroy(ctx: ProvisionContext) -> str:
    """Teardown's ``cloud`` step (§15.11): the team check; the find (every pending row resolved, every object
    Slipway would adopt recorded); ``check_all`` before any delete; the deletes in Sirdar's order; the find and
    the deletes once more (a lost answer of this run's own temporary key, or anything that appeared meanwhile);
    the leftover ACME challenge records for the environment's names. Returns ``Nothing of <env> is left on
    DigitalOcean.``"""
    env = await _env(ctx)
    account = await _account(ctx, env)
    try:
        async with DigitalOceanClient(account.secret or "", redactor=ctx.redactor) as client:
            env = await team_check(ctx, client, env, account)
            td = _Teardown(ctx, env, account, client)
            for _round in (1, 2):  # the second find catches a lost answer of this run's own temporary key
                try:
                    await sweep(td)
                    await check_all(td)
                except BaseException:
                    await td.close()
                    raise
                await _delete_all(td)  # deletes the temporary key in its finally
            left = await _leftovers(td)
            if left:
                raise ProvisionError(f"These are still there after the teardown: {', '.join(left[:10])}. Retry the "
                                     "delete, or remove them in DigitalOcean")
    except _STEP_ERRORS as exc:
        raise step_error(account.name, exc) from None
    await _sweep_challenges(ctx, env)
    done = f"Nothing of {env.name} is left on DigitalOcean."
    await ctx.say(done)
    return done


async def _sweep_challenges(ctx: ProvisionContext, env: Environment) -> None:
    """§15.11 step 6: ACME challenge records Slipway left for the environment's names. A failure is logged only:
    the records are harmless and the next order sweeps them too."""
    names = [str(h.get("hostname")) for h in env.hostnames or () if h.get("hostname")]
    if not names:
        return
    async with ctx.db() as db:
        config = await cloudflare.load_config(db)
    if config is None:
        return
    ctx.redactor.add(config.token)
    try:
        async with _challenge_records(ctx, config) as txt:
            await certs.sweep_challenges(txt, names, ctx.say)
    except cloudflare.CloudflareError as exc:
        await ctx.say(f"Couldn't check Cloudflare for left-over challenge records ({exc})")
