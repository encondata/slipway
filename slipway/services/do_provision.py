def spaces_key_spec(client: DigitalOceanClient, env: Environment, *, bucket: str, setup: bool) -> CreateSpec:
    """The bucket's own read-write key (its secret recorded with the row) or a temporary full-access setup key
    (its secret kept in memory only). A key whose answer was lost is deleted and made again (§6.2)."""
    grants = [{"bucket": "", "permission": "fullaccess"}] if setup else [{"bucket": bucket, "permission": "readwrite"}]
    role = "setup" if setup else "bucket"

    def name(nonce: str) -> str:
        return do_rules.spaces_key_name(env.name, env.id, nonce, setup=setup)

    async def find(_nonce: str, row_name: str) -> dict[str, Any] | None:
        return next((k for k in await client.spaces_keys() if k.get("name") == row_name), None)

    async def discard(key: dict[str, Any]) -> None:
        await client.delete_spaces_key(key["access_key"])

    def same(row: Resource) -> bool:
        return (do_rules.spaces_key_is_ours(row.name, env.name, env.id)
                and do_rules.spaces_key_is_setup(row.name, env.name, env.id) == setup)

    return CreateSpec(
        kind="spaces_key", name=name, body=lambda nonce: {"name": name(nonce), "grants": grants},
        send=lambda body: client.create_spaces_key(body["name"], body["grants"]), find=find,
        ident=lambda k: str(k["access_key"]),
        details=lambda k: {"bucket": bucket, "permission": grants[0]["permission"], "role": role},
        credentials=(lambda k: None) if setup else (lambda k: {"secret_key": k.get("secret_key")}),
        find_rule="its name", adoptable=lambda k: False, discard=discard, same_pending=same,
    )


def bucket_spec(env: Environment, bucket: str, *, region: str,
                s3: Callable[[], Awaitable[spaces.SpacesClient]], rebuild: bool = False) -> CreateSpec:
    """The bucket (§10.3): made with the setup key; a lost answer is found with a HEAD under it."""

    async def find(_nonce: str, _name: str) -> dict[str, Any] | None:
        return {"name": bucket} if await (await s3()).bucket_exists(bucket) else None

    async def send(_body: dict[str, Any]) -> dict[str, Any]:
        try:
            await (await s3()).create_bucket(bucket)
        except spaces.BucketTaken as exc:
            raise ProvisionError(f"{exc}. {CHANGED_NOTHING}") from None
        return {"name": bucket}

    def nothing_made(exc: BaseException) -> bool:
        if isinstance(exc, ProvisionError):  # the name is another account's
            return True
        return isinstance(exc, spaces.SpacesError) and exc.status in (400, 403)

    return CreateSpec(
        kind="bucket", name=bucket, body=lambda nonce: {"name": bucket, "region": region}, send=send, find=find,
        ident=lambda b: bucket, details=lambda b: {"region": region, "endpoint": spaces.endpoint(region)},
        find_rule="a HEAD under Slipway's key", nothing_made=nothing_made, rebuild=rebuild,
    )


