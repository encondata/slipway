async def slot_values(db: AsyncSession, env: Environment, slot_instance: Instance | None, *,
                      man: manifest.Manifest, secrets: dict[str, str] | None = None
                      ) -> tuple[dict[str, dict[str, str]], dict[str, str]]:
    """What a DigitalOcean slot's plan takes (§5.3, §11.5): ``data_values`` for ``data.attach`` from the managed
    objects (``{need: {field: value}}``) and ``edge_values`` (``{address, trusted}``: the load balancer's IP and
    the VPC's range). The role's password is read from ``secrets`` (the ones the job renders) when given, else
    the environment's stored secrets. Read in the caller's session; raises ProvisionError naming what isn't made
    yet."""
    if slot_instance is not None and slot_instance.environment_id != env.id:
        raise ProvisionError(f"{slot_instance.name} isn't one of {env.name}'s slots")
    cloud = env.cloud or {}
    region = str(cloud.get("region") or "")
    values: dict[str, dict[str, str]] = {}
    if (pg := postgres_need(man)) is not None:
        assert man.data.managed is not None
        rows = await resources.owned(db, env.id, PROVIDER, "database")
        details = (rows[0].details or {}) if rows else {}
        if not rows or not details.get("host"):
            raise ProvisionError(f"{env.name}'s database cluster isn't set up yet: deploy to a slot first")
        spec = man.data.managed.needs[pg]
        source = secrets if secrets is not None else (env.app_secrets or {})
        secret = source.get(man.data.managed.password_secret(pg)) or ""
        values[pg] = {"host": str(details["host"]), "port": str(details.get("port") or ""),
                      "database": str(spec.get("database")), "user": str(spec.get("user")), "password": secret,
                      "tls": DB_TLS, "ca_b64": str(details.get("ca_b64") or "")}
    if (s3 := objects_need(man)) is not None:
        buckets = await resources.owned(db, env.id, PROVIDER, "bucket")
        key = next((r for r in await resources.owned(db, env.id, PROVIDER, "spaces_key")
                    if (r.details or {}).get("role") == "bucket"), None)
        secret = ((key.credentials or {}).get("secret_key") if key is not None else None) or ""
        if not buckets or key is None or not secret:
            raise ProvisionError(f"{env.name}'s bucket and its key aren't made yet: deploy to a slot first")
        values[s3] = {"endpoint": spaces.endpoint(region), "region": region, "bucket": buckets[0].provider_id,
                      "access_key": key.provider_id, "secret_key": secret, "path_style": "false"}
    edge_values = {k: str(v) for k, v in (("address", cloud.get("lb_ip")), ("trusted", cloud.get("vpc_range"))) if v}
    return values, edge_values


